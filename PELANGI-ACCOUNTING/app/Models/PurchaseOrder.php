<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;
use App\Traits\HasAutoGeneratedCode;
use App\Traits\Journalable;

class PurchaseOrder extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode, Journalable;

    protected function getDocumentType(): string
    {
        return 'purchase_order';
    }

    protected function getCodeFieldName(): string
    {
        return 'purchase_order_no';
    }

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }
            
            // Set company_id from global selector if not explicitly set
            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });

        static::deleting(function ($model) {
            $hasLockedReceipts = $model->goodsReceipts()->where('is_locked', true)->exists();
            $hasLockedInvoices = \Illuminate\Support\Facades\DB::table('purchase_invoices')
                ->where('purchase_order_id', $model->id)
                ->where('is_locked', true)
                ->whereNull('deleted_at')
                ->exists();
            
            if ($hasLockedReceipts || $hasLockedInvoices) {
                \Filament\Notifications\Notification::make()
                    ->danger()
                    ->title('Cannot delete')
                    ->body('This order has locked goods receipts or invoices.')
                    ->send();
                return false;
            }
        });

    }

    /**
     * The attributes that are mass assignable.
     *
     * @var array
     */
    protected $fillable = [
        'purchase_order_no',
        'date',
        'is_closed',
        'reference_no',
        'valid_until',
        'description',
        'other_charges',
        'discount',
        'discount_percentage',
        'subtotal',
        'tax_amount',
        'total',
        'total_amount',
        'status',
        'receipt_meta',
        'invoice_meta',
        'supplier_id',
        'other_charges_account_id',
        'discount_account_id',
        'company_id',
        'created_by_user_id',
        'updated_by_user_id',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'date' => 'date',
            'is_closed' => 'boolean',
            'valid_until' => 'date',
            'other_charges' => 'decimal:2',
            'discount' => 'decimal:2',
            'discount_percentage' => 'decimal:2',
            'subtotal' => 'decimal:2',
            'tax_amount' => 'decimal:2',
            'total' => 'decimal:2',
            'total_amount' => 'decimal:2',
            'status' => 'string',
            'receipt_meta' => 'array',
            'invoice_meta' => 'array',
            'supplier_id' => 'integer',
            'other_charges_account_id' => 'integer',
            'discount_account_id' => 'integer',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
            'updated_by_user_id' => 'integer',
        ];
    }

    public function supplier(): BelongsTo
    {
        return $this->belongsTo(Contact::class);
    }

    public function otherChargesAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function discountAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function updatedByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function items(): HasMany
    {
        return $this->hasMany(PurchaseOrderItem::class);
    }

    public function recalculateTotalsFromItems(): void
    {
        $items = $this->items()->get(['total', 'tax_id']);
        $subtotal = (float) $items->sum('total');
        $discountPercentage = (float) ($this->discount_percentage ?? 0);
        $discount = (float) ($this->discount ?? 0);
        $otherCharges = (float) ($this->other_charges ?? 0);
        $taxAmount = 0.0;

        if ($discountPercentage > 0 && $subtotal > 0) {
            $discount = $subtotal * ($discountPercentage / 100);
        }

        $taxIds = $items->pluck('tax_id')->filter()->unique()->values();
        $taxesById = $taxIds->isEmpty()
            ? collect()
            : \App\Models\Tax::query()->whereIn('id', $taxIds)->get()->keyBy('id');

        foreach ($items as $item) {
            $lineTotal = (float) ($item->total ?? 0);
            $taxId = $item->tax_id;
            if (!$taxId) {
                continue;
            }

            $tax = $taxesById->get($taxId);
            $taxPercentage = (float) ($tax?->tax_percentage ?? 0);
            if ($taxPercentage <= 0) {
                continue;
            }

            $lineDiscount = $lineTotal * ($discountPercentage / 100);
            $taxBase = $lineTotal - $lineDiscount;
            $taxAmount += $taxBase * ($taxPercentage / 100);
        }

        $this->subtotal = $subtotal;
        $this->discount = $discount;
        $this->tax_amount = $taxAmount;
        $this->total_amount = $subtotal - $discount + $otherCharges + $taxAmount;
    }

    public function approveWithWisma(?string $comment = null): array
    {
        $wismaService = app(\App\Services\WismaService::class);
        $result = $wismaService->syncApprovedPurchaseOrder($this, $comment);

        if (!($result['success'] ?? false)) {
            return $result;
        }

        $this->forceFill([
            'status' => 'approved',
            'updated_by_user_id' => auth()->id(),
        ])->saveQuietly();

        return $result;
    }

    public function rejectWithWisma(?string $comment = null): array
    {
        $wismaService = app(\App\Services\WismaService::class);
        $result = $wismaService->syncRejectedPurchaseOrder($this, $comment);

        if (!($result['success'] ?? false)) {
            return $result;
        }

        $this->forceFill([
            'status' => 'rejected',
            'updated_by_user_id' => auth()->id(),
        ])->saveQuietly();

        return $result;
    }

    public function computeReceiptMeta(): array
    {
        $items = $this->items()->get(['quantity', 'received_quantity']);
        $totalQty = (float) $items->sum('quantity');
        $receivedQty = (float) $items->sum('received_quantity');
        $remainingQty = max(0.0, $totalQty - $receivedQty);

        return [
            'total' => round($totalQty, 2),
            'received' => round($receivedQty, 2),
            'remaining' => round($remainingQty, 2),
        ];
    }

    public function refreshReceiptTracking(): void
    {
        $receiptQuantities = \Illuminate\Support\Facades\DB::table('goods_receipts')
            ->join('goods_receipt_items', 'goods_receipt_items.goods_receipt_id', '=', 'goods_receipts.id')
            ->whereNull('goods_receipts.deleted_at')
            ->whereNull('goods_receipt_items.deleted_at')
            ->where('goods_receipts.is_locked', true)
            ->where('goods_receipts.purchase_order_id', $this->id)
            ->whereNotNull('goods_receipt_items.purchase_order_item_id')
            ->groupBy('goods_receipt_items.purchase_order_item_id')
            ->select([
                'goods_receipt_items.purchase_order_item_id',
                \Illuminate\Support\Facades\DB::raw('COALESCE(SUM(goods_receipt_items.quantity), 0) as received_quantity'),
            ])
            ->pluck('received_quantity', 'purchase_order_item_id');

        $items = $this->items()->get(['id', 'quantity', 'received_quantity']);

        foreach ($items as $item) {
            $received = (float) ($receiptQuantities[$item->id] ?? 0);
            $item->received_quantity = round($received, 2);
            $item->saveQuietly();
        }

        $this->receipt_meta = $this->computeReceiptMeta();
        $this->saveQuietly();
    }

    public function computeInvoiceMeta(): array
    {
        $items = $this->items()->get(['quantity', 'invoiced_quantity']);
        $totalQty = (float) $items->sum('quantity');
        $invoicedQty = (float) $items->sum('invoiced_quantity');
        $remainingQty = max(0.0, $totalQty - $invoicedQty);

        return [
            'total' => round($totalQty, 2),
            'invoiced' => round($invoicedQty, 2),
            'remaining' => round($remainingQty, 2),
        ];
    }

    public function refreshInvoiceTracking(): void
    {
        $invoiceQuantities = \Illuminate\Support\Facades\DB::table('purchase_invoices')
            ->join('purchase_invoice_items', 'purchase_invoice_items.purchase_invoice_id', '=', 'purchase_invoices.id')
            ->whereNull('purchase_invoices.deleted_at')
            ->whereNull('purchase_invoice_items.deleted_at')
            ->where('purchase_invoices.is_locked', true)
            ->where('purchase_invoices.purchase_order_id', $this->id)
            ->whereNotNull('purchase_invoice_items.purchase_order_item_id')
            ->groupBy('purchase_invoice_items.purchase_order_item_id')
            ->select([
                'purchase_invoice_items.purchase_order_item_id',
                \Illuminate\Support\Facades\DB::raw('COALESCE(SUM(purchase_invoice_items.quantity), 0) as invoiced_quantity'),
            ])
            ->pluck('invoiced_quantity', 'purchase_order_item_id');

        $items = $this->items()->get(['id', 'quantity', 'invoiced_quantity']);

        foreach ($items as $item) {
            $invoiced = (float) ($invoiceQuantities[$item->id] ?? 0);
            $item->invoiced_quantity = round($invoiced, 2);
            $item->saveQuietly();
        }

        $this->invoice_meta = $this->computeInvoiceMeta();
        $this->saveQuietly();
    }

    public function goodsReceipts(): HasMany
    {
        return $this->hasMany(GoodsReceipt::class);
    }

    public function purchaseInvoices(): HasMany
    {
        return $this->hasMany(PurchaseInvoice::class);
    }

    /**
     * Get the received quantity for all items in this purchase order
     */
    public function getReceivedQuantityAttribute(): float
    {
        return $this->goodsReceipts()
            ->where('status', '!=', 'cancelled')
            ->with('items')
            ->get()
            ->flatMap->items
            ->sum('quantity');
    }

    /**
     * Get the total quantity for all items in this purchase order
     */
    public function getTotalQuantityAttribute(): float
    {
        return $this->items->sum('quantity');
    }

    /**
     * Check if the purchase order is fully received
     */
    public function getIsFullyReceivedAttribute(): bool
    {
        return $this->total_quantity > 0 && $this->received_quantity >= $this->total_quantity;
    }

    /**
     * Check if the purchase order is partially received
     */
    public function getIsPartiallyReceivedAttribute(): bool
    {
        return $this->received_quantity > 0 && $this->received_quantity < $this->total_quantity;
    }

    public function journalEntries()
    {
        return $this->hasMany(\App\Models\JournalEntry::class, 'reference_id')
            ->where('reference_type', PurchaseOrder::class);
    }

    public function isPoExist($po_code)
    {
        return self::where('purchase_order_no', $po_code)->exists();
    }
}
