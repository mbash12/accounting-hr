<?php

namespace App\Models;

use App\Traits\HasAutoGeneratedCode;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;

class Payslip extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode;

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }

            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId) {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });
    }

    protected function getDocumentType(): string
    {
        return 'payslip';
    }

    protected function getCodeFieldName(): string
    {
        return 'number';
    }

    protected $fillable = [
        'number',
        'employee_id',
        'payroll_period_id',
        'basic_salary',
        'total_allowance',
        'total_deduction',
        'gross_salary',
        'taxable_income',
        'pph21',
        'bpjs_kesehatan_employee',
        'bpjs_kesehatan_employer',
        'bpjs_ketenagakerjaan_employee',
        'bpjs_ketenagakerjaan_employer',
        'net_salary',
        'company_id',
        'created_by_user_id',
    ];

    protected function casts(): array
    {
        return [
            'basic_salary' => 'decimal:2',
            'total_allowance' => 'decimal:2',
            'total_deduction' => 'decimal:2',
            'gross_salary' => 'decimal:2',
            'taxable_income' => 'decimal:2',
            'pph21' => 'decimal:2',
            'bpjs_kesehatan_employee' => 'decimal:2',
            'bpjs_kesehatan_employer' => 'decimal:2',
            'bpjs_ketenagakerjaan_employee' => 'decimal:2',
            'bpjs_ketenagakerjaan_employer' => 'decimal:2',
            'net_salary' => 'decimal:2',
            'employee_id' => 'integer',
            'payroll_period_id' => 'integer',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
        ];
    }

    public function employee(): BelongsTo
    {
        return $this->belongsTo(Employee::class);
    }

    public function payrollPeriod(): BelongsTo
    {
        return $this->belongsTo(PayrollPeriod::class);
    }

    public function items(): HasMany
    {
        return $this->hasMany(PayslipItem::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by_user_id');
    }
}
