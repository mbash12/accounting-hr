<?php

namespace App\Models;

use App\Traits\HasAutoGeneratedCode;
use App\Traits\HasDependencyValidation;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;

class Tax extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode, HasDependencyValidation;

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }
            
            // Set company_id from global selector if not explicitly set
            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId) {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });
    }

    protected function getDocumentType(): string
    {
        return 'tax';
    }

    protected function getCodeFieldName(): string
    {
        return 'code';
    }

    /**
     * The attributes that are mass assignable.
     *
     * @var array
     */
    protected $fillable = [
        'name',
        'code',
        'tax_percentage',
        'tax_type',
        'is_purchase_tax',
        'is_sales_tax',
        'effective_date',
        'expiry_date',
        'compound_tax',
        'is_active',
        'purchase_account_id',
        'sales_account_id',
        'company_id',
        'created_by_user_id',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'tax_percentage' => 'decimal:2',
            'is_purchase_tax' => 'boolean',
            'is_sales_tax' => 'boolean',
            'effective_date' => 'date',
            'expiry_date' => 'date',
            'compound_tax' => 'boolean',
            'is_active' => 'boolean',
            'purchase_account_id' => 'integer',
            'sales_account_id' => 'integer',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
        ];
    }

    public function purchaseAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function salesAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function getDependencyChecks(): array
    {
        return [
            ['table' => 'products', 'foreignKey' => 'tax_id', 'label' => 'products'],
            ['table' => 'sales_order_items', 'foreignKey' => 'tax_id', 'label' => 'sales order items'],
            ['table' => 'purchase_order_items', 'foreignKey' => 'tax_id', 'label' => 'purchase order items'],
            ['table' => 'sales_invoice_items', 'foreignKey' => 'tax_id', 'label' => 'sales invoice items'],
            ['table' => 'purchase_invoice_items', 'foreignKey' => 'tax_id', 'label' => 'purchase invoice items'],
        ];
    }
}
