<?php

namespace App\Models;

use App\Traits\HasAutoGeneratedCode;
use App\Traits\HasDependencyValidation;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Log;

class Unit extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode, HasDependencyValidation;

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }

            // Set company_id from global selector if not explicitly set
            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId) {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });

        static::created(function ($model) {
            $model->syncToWisma('update');
        });

        static::updated(function ($model) {
            if ($model->wasChanged(['code', 'name', 'description', 'is_active', 'unit_category_id', 'conversion_factor', 'deleted_at'])) {
                $model->syncToWisma('update');
            }
        });

        static::deleted(function ($model) {
            $model->syncToWisma('delete');
        });

        static::restored(function ($model) {
            $model->syncToWisma('update');
        });
    }

    protected function getDocumentType(): string
    {
        return 'unit_measurement';
    }

    protected function getCodeFieldName(): string
    {
        return 'code';
    }

    /**
     * The attributes that are mass assignable.
     *
     * @var array
     */
    protected $fillable = [
        'code',
        'name',
        'description',
        'is_active',
        'unit_category_id',
        'conversion_factor',
        'company_id',
        'created_by_user_id',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'is_active' => 'boolean',
            'unit_category_id' => 'integer',
            'conversion_factor' => 'decimal:6',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
        ];
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function unitCategory(): BelongsTo
    {
        return $this->belongsTo(UnitCategory::class);
    }

    protected function syncToWisma(string $action): void
    {
        try {
            $wismaService = app(\App\Services\WismaService::class);

            if (!$wismaService->shouldSyncUom()) {
                return;
            }

            $wismaService->syncUom($this, $action);
        } catch (\Throwable $e) {
            Log::error('Failed to sync UOM to Wisma from model event: ' . $e->getMessage(), [
                'exception' => $e,
                'unit_id' => $this->id,
                'code' => $this->code,
                'action' => $action,
            ]);
        }
    }

    public function getDependencyChecks(): array
    {
        return [
            ['table' => 'products', 'foreignKey' => 'unit_id', 'label' => 'products'],
            ['table' => 'sales_order_items', 'foreignKey' => 'unit_id', 'label' => 'sales order items'],
            ['table' => 'purchase_order_items', 'foreignKey' => 'unit_id', 'label' => 'purchase order items'],
            ['table' => 'delivery_document_items', 'foreignKey' => 'unit_id', 'label' => 'delivery document items'],
            ['table' => 'goods_receipt_items', 'foreignKey' => 'unit_id', 'label' => 'goods receipt items'],
            ['table' => 'sales_invoice_items', 'foreignKey' => 'unit_id', 'label' => 'sales invoice items'],
            ['table' => 'purchase_invoice_items', 'foreignKey' => 'unit_id', 'label' => 'purchase invoice items'],
        ];
    }
}
