<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;

class PurchaseInvoice extends Model
{
    use HasFactory, SoftDeletes, \App\Traits\HasAutoGeneratedCode, \App\Traits\Journalable, \App\Traits\HasDependencyValidation;

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }
            
            // Set company_id from global selector if not explicitly set
            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });

        static::updating(function (self $model) {
            if (!$model->getOriginal('is_locked')) {
                return;
            }

            $model->supplier_id = $model->getOriginal('supplier_id');
            $model->purchase_order_id = $model->getOriginal('purchase_order_id');
            $model->goods_receipt_id = $model->getOriginal('goods_receipt_id');
            $model->company_id = $model->getOriginal('company_id');
            $model->job_id = $model->getOriginal('job_id');
            $model->is_locked = true;
        });

        static::saved(function ($model) {
            if ($model->is_locked && $model->purchase_order_id) {
                $model->purchaseOrder?->refreshInvoiceTracking();
            }
        });

        static::deleted(function ($model) {
            if ($model->is_locked && $model->purchase_order_id) {
                $model->purchaseOrder?->refreshInvoiceTracking();
            }
        });

        static::restored(function ($model) {
            if ($model->is_locked && $model->purchase_order_id) {
                $model->purchaseOrder?->refreshInvoiceTracking();
            }
        });
    }

    /**
     * The attributes that are mass assignable.
     *
     * @var array
     */
    protected $fillable = [
        'invoice_number',
        'date',
        'due_date',
        'payment_term_id',
        'is_paid',
        'is_locked',
        'reference_no',
        'description',
        'other_charges',
        'discount',
        'discount_percentage',
        'advance_payment',
        'subtotal',
        'tax_amount',
        'total',
        'paid_amount',
        'outstanding_amount',
        'status',
        'supplier_id',
        'purchase_order_id',
        'goods_receipt_id',
        'job_id',
        'other_charges_account_id',
        'discount_account_id',
        'advance_payment_account_id',
        'company_id',
        'created_by_user_id',
        'updated_by_user_id',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'date' => 'date',
            'due_date' => 'date',
            'is_paid' => 'boolean',
            'is_locked' => 'boolean',
            'other_charges' => 'decimal:2',
            'discount' => 'decimal:2',
            'discount_percentage' => 'decimal:2',
            'advance_payment' => 'decimal:2',
            'subtotal' => 'decimal:2',
            'tax_amount' => 'decimal:2',
            'total' => 'decimal:2',
            'paid_amount' => 'decimal:2',
            'outstanding_amount' => 'decimal:2',
            'supplier_id' => 'integer',
            'purchase_order_id' => 'integer',
            'goods_receipt_id' => 'integer',
            'job_id' => 'integer',
            'other_charges_account_id' => 'integer',
            'discount_account_id' => 'integer',
            'advance_payment_account_id' => 'integer',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
            'updated_by_user_id' => 'integer',
            'payment_term_id' => 'integer',
            'status' => 'string',
        ];
    }

    public function supplier(): BelongsTo
    {
        return $this->belongsTo(Contact::class);
    }

    public function purchaseOrder(): BelongsTo
    {
        return $this->belongsTo(PurchaseOrder::class);
    }

    public function goodsReceipt(): BelongsTo
    {
        return $this->belongsTo(GoodsReceipt::class);
    }

    public function job(): BelongsTo
    {
        return $this->belongsTo(Project::class);
    }

    public function otherChargesAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function discountAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function advancePaymentAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function updatedByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function items(): HasMany
    {
        return $this->hasMany(PurchaseInvoiceItem::class);
    }

    public function otherCharges(): HasMany
    {
        return $this->hasMany(PurchaseInvoiceOtherCharge::class)->orderBy('sort_order')->orderBy('id');
    }

    public function syncOtherChargesTotal(): float
    {
        return \App\Services\AdditionalChargesHelper::syncTotal($this);
    }

    public function paymentTerm(): BelongsTo
    {
        return $this->belongsTo(PaymentTerm::class);
    }

    /**
     * Calculate due date based on payment term
     */
    public function calculateDueDate(): void
    {
        if ($this->paymentTerm && $this->date) {
            $this->due_date = \Carbon\Carbon::parse($this->date)
                ->addDays($this->paymentTerm->due_days);
        }
    }

    /**
     * Update due date based on current payment term
     */
    public function updateDueDate(): void
    {
        $this->calculateDueDate();
        $this->saveQuietly();
    }

    public function journalEntries()
    {
        return $this->hasMany(\App\Models\JournalEntry::class, 'reference_id')
            ->where('reference_type', PurchaseInvoice::class);
    }

    public function journalEntry(): \Illuminate\Database\Eloquent\Relations\HasOne
    {
        return $this->hasOne(\App\Models\JournalEntry::class, 'reference_id')
            ->where('reference_type', self::class);
    }

    /**
     * Get the total amount attribute (alias for total)
     */
    public function getTotalAmountAttribute(): float
    {
        return $this->total ?? 0;
    }

    /**
     * Get the document type for purchase invoices
     */
    protected function getDocumentType(): string
    {
        return 'purchase_invoice';
    }

    /**
     * Get the code field name for purchase invoices
     */
    protected function getCodeFieldName(): string
    {
        return 'invoice_number';
    }

    public function getDependencyChecks(): array
    {
        return [
            ['table' => 'payable_payment_items', 'foreignKey' => 'purchase_invoice_id', 'label' => 'payable payments'],
            ['table' => 'purchase_returns', 'foreignKey' => 'purchase_invoice_id', 'label' => 'purchase returns'],
        ];
    }
}
