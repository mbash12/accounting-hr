<?php

namespace App\Models;

use App\Traits\HasAutoGeneratedCode;
use App\Traits\HasDependencyValidation;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;

class Employee extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode, HasDependencyValidation;

    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }

            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId) {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });
    }

    protected function getDocumentType(): string
    {
        return 'employee';
    }

    protected function getCodeFieldName(): string
    {
        return 'employee_id';
    }

    protected $fillable = [
        'name',
        'email',
        'password',
        'employee_id',
        'nik',
        'npwp',
        'department_id',
        'position',
        'hire_date',
        'status',
        'ptkp_status',
        'bank_name',
        'bank_account_number',
        'bank_account_holder',
        'bpjs_kesehatan_number',
        'bpjs_ketenagakerjaan_number',
        'basic_salary',
        'is_active',
        'company_id',
        'foto',
        'foto_vector',
        'created_by_user_id',
    ];

    protected $hidden = [
        'password',
    ];

    protected function casts(): array
    {
        return [
            'hire_date' => 'date',
            'basic_salary' => 'decimal:2',
            'is_active' => 'boolean',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
            'password' => 'hashed',
        ];
    }

    public function department(): BelongsTo
    {
        return $this->belongsTo(Department::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class, 'created_by_user_id');
    }

    public function salaryComponents(): HasMany
    {
        return $this->hasMany(EmployeeSalaryComponent::class);
    }

    public function attendances(): HasMany
    {
        return $this->hasMany(Attendance::class);
    }

    public function permits(): HasMany
    {
        return $this->hasMany(Permit::class);
    }

    public function overtimeLogs(): HasMany
    {
        return $this->hasMany(OvertimeLog::class);
    }

    public function leaveQuotas(): HasMany
    {
        return $this->hasMany(EmployeeLeaveQuota::class);
    }

    public function payslips(): HasMany
    {
        return $this->hasMany(Payslip::class);
    }

    public function getDependencyChecks(): array
    {
        return [
            ['relation' => 'attendances', 'label' => 'attendance records'],
            ['relation' => 'permits', 'label' => 'permit records'],
            ['relation' => 'overtimeLogs', 'label' => 'overtime logs'],
            ['relation' => 'payslips', 'label' => 'payslips'],
        ];
    }
}
