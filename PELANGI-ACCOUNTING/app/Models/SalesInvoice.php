<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Facades\Auth;
use App\Traits\HasAutoGeneratedCode;
use App\Traits\HasDependencyValidation;
use App\Traits\Journalable;
use App\Traits\EnforcesOpenPeriod;

class SalesInvoice extends Model
{
    use HasFactory, SoftDeletes, HasAutoGeneratedCode, Journalable, HasDependencyValidation, EnforcesOpenPeriod;

    protected function getDocumentType(): string
    {
        return 'sales_invoice';
    }

    protected function getCodeFieldName(): string
    {
        return 'invoice_number';
    }


    protected static function boot()
    {
        parent::boot();

        static::creating(function ($model) {
            if (Auth::check() && !$model->created_by_user_id) {
                $model->created_by_user_id = Auth::id();
            }

            // Set company_id from global selector if not explicitly set
            if (!$model->company_id) {
                $selectedCompanyId = session('selected_company_id');
                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                    $model->company_id = $selectedCompanyId;
                }
            }
        });

        static::updating(function (self $model) {
            if (!$model->getOriginal('is_locked')) {
                return;
            }

            $model->customer_id = $model->getOriginal('customer_id');
            $model->sales_order_id = $model->getOriginal('sales_order_id');
            $model->company_id = $model->getOriginal('company_id');
            $model->job_id = $model->getOriginal('job_id');
            $model->is_locked = true;
        });

        static::saved(function ($model) {
            if ($model->is_locked && $model->sales_order_id) {
                $model->salesOrder?->refreshInvoiceTracking();
            }
        });

        static::deleted(function ($model) {
            if ($model->is_locked && $model->sales_order_id) {
                $model->salesOrder?->refreshInvoiceTracking();
            }
        });

        static::restored(function ($model) {
            if ($model->is_locked && $model->sales_order_id) {
                $model->salesOrder?->refreshInvoiceTracking();
            }
        });
    }

    /**
     * The attributes that are mass assignable.
     *
     * @var array
     */
    protected $fillable = [
        'invoice_number',
        'date',
        'due_date',
        'is_paid',
        'reference_no',
        'description',
        'other_charges',
        'discount',
        'subtotal',
        'tax_amount',
        'total_amount',
        'paid_amount',
        'outstanding_amount',
        'is_advance_payment_invoice',
        'is_settlement_invoice',
        'is_locked',
        'status',
        'customer_id',
        'payment_term_id',
        'sales_order_id',
        'job_id',
        'other_charges_account_id',
        'discount_account_id',
        'company_id',
        'created_by_user_id',
        'updated_by_user_id',
    ];

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'id' => 'integer',
            'date' => 'date',
            'due_date' => 'date',
            'is_paid' => 'boolean',
            'other_charges' => 'decimal:2',
            'discount' => 'decimal:2',
            'subtotal' => 'decimal:2',
            'tax_amount' => 'decimal:2',
            'total_amount' => 'decimal:2',
            'paid_amount' => 'decimal:2',
            'outstanding_amount' => 'decimal:2',
            'is_advance_payment_invoice' => 'boolean',
            'is_settlement_invoice' => 'boolean',
            'is_locked' => 'boolean',
            'customer_id' => 'integer',
            'payment_term_id' => 'integer',
            'sales_order_id' => 'integer',
            'job_id' => 'integer',
            'other_charges_account_id' => 'integer',
            'discount_account_id' => 'integer',
            'company_id' => 'integer',
            'created_by_user_id' => 'integer',
            'updated_by_user_id' => 'integer',
            'status' => 'string',
        ];
    }

    public function customer(): BelongsTo
    {
        return $this->belongsTo(Contact::class);
    }

    public function paymentTerm(): BelongsTo
    {
        return $this->belongsTo(PaymentTerm::class);
    }

    public function salesOrder(): BelongsTo
    {
        return $this->belongsTo(SalesOrder::class);
    }

    public function job(): BelongsTo
    {
        return $this->belongsTo(Project::class);
    }

    public function otherChargesAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function discountAccount(): BelongsTo
    {
        return $this->belongsTo(Account::class);
    }

    public function journalEntries()
    {
        return $this->hasMany(\App\Models\JournalEntry::class, 'reference_id')
            ->where('reference_type', SalesInvoice::class);
    }

    public function journalEntry(): \Illuminate\Database\Eloquent\Relations\HasOne
    {
        return $this->hasOne(\App\Models\JournalEntry::class, 'reference_id')
            ->where('reference_type', self::class);
    }

    public function company(): BelongsTo
    {
        return $this->belongsTo(Company::class);
    }

    public function createdByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function updatedByUser(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    public function items(): HasMany
    {
        return $this->hasMany(SalesInvoiceItem::class);
    }

    public function otherCharges(): HasMany
    {
        return $this->hasMany(SalesInvoiceOtherCharge::class)->orderBy('sort_order')->orderBy('id');
    }

    public function syncOtherChargesTotal(): float
    {
        return \App\Services\AdditionalChargesHelper::syncTotal($this);
    }

    /**
     * Calculate due date based on payment term
     *
     * @return \Carbon\Carbon|null
     */
    public function calculateDueDate(): ?\Carbon\Carbon
    {
        if (!$this->date) {
            return null;
        }

        $dueDays = $this->paymentTerm?->due_days ?? 0;
        return $this->date->copy()->addDays($dueDays);
    }

    /**
     * Update due date based on payment term
     *
     * @return void
     */
    public function updateDueDate(): void
    {
        $this->due_date = $this->calculateDueDate();
        $this->saveQuietly();
    }

    public function getDependencyChecks(): array
    {
        return [
            ['table' => 'receivable_payment_items', 'foreignKey' => 'sales_invoice_id', 'label' => 'receivable payments'],
            ['table' => 'sales_return_items', 'foreignKey' => 'sales_invoice_id', 'label' => 'sales returns'],
        ];
    }
}
