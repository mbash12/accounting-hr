<?php

namespace App\Filament\Resources\Departments\Schemas;

use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

use Filament\Forms\Components\CheckboxList;
use Filament\Forms\Components\TimePicker;

class DepartmentForm
{
    use HasAutoGeneratedCode;

    protected function getDocumentType(): string
    {
        return 'department';
    }

    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make(__('Department Information'))
                    ->schema([
                        TextInput::make('name')
                            ->required()
                            ->label(__('Department Name')),
                        (new static)->getCodeField('code', __('Department Code'))
                            ->rule('required'),
                        Toggle::make('is_active')
                            ->required()
                            ->label(__('Active'))
                            ->default(true),
                    ])
                    ->columns(2),
                Section::make(__('Work Schedule'))
                    ->description(__('Work hours are now configured per shift type in the Shift Schedule module. The fields below are kept for backward compatibility but are not used.'))
                    ->schema([
                        TimePicker::make('work_start_time')
                            ->label(__('Start Time'))
                            ->default('08:00:00')
                            ->disabled()
                            ->dehydrated(false)
                            ->helperText(__('Deprecated — use Shift Types instead.')),
                        TimePicker::make('work_end_time')
                            ->label(__('End Time'))
                            ->default('17:00:00')
                            ->disabled()
                            ->dehydrated(false)
                            ->helperText(__('Deprecated — use Shift Types instead.')),
                        CheckboxList::make('working_days')
                            ->label(__('Working Days'))
                            ->options([
                                'Monday' => __('Monday'),
                                'Tuesday' => __('Tuesday'),
                                'Wednesday' => __('Wednesday'),
                                'Thursday' => __('Thursday'),
                                'Friday' => __('Friday'),
                                'Saturday' => __('Saturday'),
                                'Sunday' => __('Sunday'),
                            ])
                            ->columns(3)
                            ->default(['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday'])
                            ->disabled()
                            ->dehydrated(false)
                            ->helperText(__('Deprecated — use Shift Schedule upload instead.'))
                            ->columnSpanFull(),
                    ])
                    ->columns(2)
                    ->collapsed()
                    ->persistCollapsed(),
                Section::make(__('System'))
                    ->collapsible()
                    ->schema([
                        Select::make('company_id')
                            ->relationship(
                                name: 'company',
                                titleAttribute: 'name'
                            )
                            ->disabled()
                            ->label(__('Company')),
                        Select::make('created_by_user_id')
                            ->relationship('createdByUser', 'name')
                            ->disabled()
                            ->label(__('Created By')),
                    ])
                    ->columns(2)
                    ->hidden(),
            ]);
    }
}
