<?php

namespace App\Filament\Resources\Taxes\Schemas;

use App\Filament\Forms\Components\NumberInput;
use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

class TaxForm
{
    use HasAutoGeneratedCode;

    protected function getDocumentType(): string
    {
        return 'tax';
    }

    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__("Informasi Pajak"))
                ->schema([
                    TextInput::make("name")
                        ->label(__("Nama Pajak"))
                        ->required()
                        ->columnSpanFull(),
                    (new static)->getCodeField('code', __('Kode Pajak'))
                        ->rule('required')
                        ->rule(function (?\App\Models\Tax $record) {
                            return function (string $attribute, $value, \Closure $fail) use ($record) {
                                $query = \App\Models\Tax::where('code', $value);

                                if ($record && $record->id) {
                                    // Editing: exclude current record
                                    $query->where('id', '!=', $record->id);
                                }

                                // Scope to the same company
                                if ($record && $record->company_id) {
                                    $query->where('company_id', $record->company_id);
                                } else {
                                    $companyId = session('selected_company_id') ?? auth()->user()->companies()->first()?->id;
                                    $query->where('company_id', $companyId);
                                }

                                if ($query->exists()) {
                                    $fail(__('The :attribute has already been taken.'));
                                }
                            };
                        }),
                    NumberInput::make("tax_percentage")
                        ->label(__("Persentase Pajak"))
                        ->required()
                        ->suffix("%")
                        ->decimal(true),
                    Textarea::make("description")
                        ->label(__("Keterangan"))
                        ->columnSpanFull(),
                    Toggle::make("is_active")->required()->label(__("Aktif")),
                ])
                ->columns(2),



            Section::make(__("Pemetaan Akun"))
                ->schema([
                    Select::make("company_id")
                        ->relationship(
                            name: 'company',
                            titleAttribute: 'name',
                            modifyQueryUsing: function ($query) {
                                $user = auth()->user();
                                if ($user) {
                                    $userCompanyIds = $user->companies()->pluck('companies.id');
                                    if ($userCompanyIds->isNotEmpty()) {
                                        $query->whereIn('companies.id', $userCompanyIds);
                                    } else {
                                        // If user has no assigned companies, return no results
                                        $query->whereRaw('1 = 0');
                                    }
                                }
                            }
                        )
                        ->default(function () {
                            $selectedCompanyId = session('selected_company_id');
                            $user = auth()->user();
                            if ($selectedCompanyId) {
                                // Verify user has access to this company
                                if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                    return $selectedCompanyId;
                                }
                            }
                            return null;
                        })
                        ->hidden()
                        ->searchable()
                        ->preload()
                        ->required()
                        ->live()
                        ->afterStateUpdated(function ($state, callable $set) {
                            // Clear account fields when company changes
                            $set('purchase_account_id', null);
                            $set('sales_account_id', null);
                        })
                        ->label(__("Perusahaan")),
                    Select::make("purchase_account_id")
                        ->getOptionLabelUsing(function ($value) {
                            $account = \App\Models\Account::find($value);
                            return $account ? "{$account->code} - {$account->name}" : $value;
                        })
                        ->searchable()
                        ->getSearchResultsUsing(function (string $search, callable $get) {
                            // Get company from form field
                            $liveCompany = $get('company_id');
                            $globalCompanyId = session('selected_company_id');

                            // Priority: form company > global company > null
                            $companyId = $liveCompany ?: ($globalCompanyId && $globalCompanyId !== 'all' ? $globalCompanyId : null);

                            $query = \App\Models\Account::where('is_header', false)
                                ->where(function ($query) use ($search) {
                                    $query->where('code', 'like', "%{$search}%")
                                        ->orWhere('name', 'like', "%{$search}%");
                                });

                            // Only filter by company if we have a valid company ID
                            if ($companyId) {
                                $query->where('company_id', $companyId);
                            }

                            return $query->orderBy('code')->limit(50)->get()->map(fn($account) => [
                                'value' => $account->id,
                                'label' => "{$account->code} - {$account->name}",
                            ]);
                        })
                        ->options(function (callable $get) {
                            // Get company from form field
                            $liveCompany = $get('company_id');
                            $globalCompanyId = session('selected_company_id');

                            // Priority: form company > global company > null
                            $companyId = $liveCompany ?: ($globalCompanyId && $globalCompanyId !== 'all' ? $globalCompanyId : null);

                            $query = \App\Models\Account::where('is_header', false);

                            // Only filter by company if we have a valid company ID
                            if ($companyId) {
                                $query->where('company_id', $companyId);
                            }

                            return $query->orderBy('code')->limit(50)->get()->mapWithKeys(fn($account) => [
                                $account->id => "{$account->code} - {$account->name}",
                            ]);
                        })
                        ->live()
                        ->nullable()
                        ->label(__("Akun Pembelian"))
                        ->columnSpanFull(),
                    Select::make("sales_account_id")
                        ->getOptionLabelUsing(function ($value) {
                            $account = \App\Models\Account::find($value);
                            return $account ? "{$account->code} - {$account->name}" : $value;
                        })
                        ->searchable()
                        ->getSearchResultsUsing(function (string $search, callable $get) {
                            // Get company from form field
                            $liveCompany = $get('company_id');
                            $globalCompanyId = session('selected_company_id');

                            // Priority: form company > global company > null
                            $companyId = $liveCompany ?: ($globalCompanyId && $globalCompanyId !== 'all' ? $globalCompanyId : null);

                            $query = \App\Models\Account::where('is_header', false)
                                ->where(function ($query) use ($search) {
                                    $query->where('code', 'like', "%{$search}%")
                                        ->orWhere('name', 'like', "%{$search}%");
                                });

                            // Only filter by company if we have a valid company ID
                            if ($companyId) {
                                $query->where('company_id', $companyId);
                            }

                            return $query->orderBy('code')->limit(50)->get()->map(fn($account) => [
                                'value' => $account->id,
                                'label' => "{$account->code} - {$account->name}",
                            ]);
                        })
                        ->options(function (callable $get) {
                            // Get company from form field
                            $liveCompany = $get('company_id');
                            $globalCompanyId = session('selected_company_id');

                            // Priority: form company > global company > null
                            $companyId = $liveCompany ?: ($globalCompanyId && $globalCompanyId !== 'all' ? $globalCompanyId : null);

                            $query = \App\Models\Account::where('is_header', false);

                            // Only filter by company if we have a valid company ID
                            if ($companyId) {
                                $query->where('company_id', $companyId);
                            }

                            return $query->orderBy('code')->limit(50)->get()->mapWithKeys(fn($account) => [
                                $account->id => "{$account->code} - {$account->name}",
                            ]);
                        })
                        ->live()
                        ->nullable()
                        ->label(__("Akun Penjualan"))
                        ->columnSpanFull(),
                ])
                ->columns(2),


        ]);
    }
}
