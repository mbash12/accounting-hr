<?php

namespace App\Filament\Resources\Products\Schemas;

use App\Filament\Forms\Components\NumberInput;
use App\Traits\HasAutoGeneratedCode;
use Filament\Actions\Action;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Repeater\TableColumn;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Enums\Alignment;
use App\Models\Unit;

class ProductForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for products
     */
    protected function getDocumentType(): string
    {
        return 'product';
    }

    /**
     * Get the code field name for products
     */
    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__("Product Information"))
                ->schema([
                    TextInput::make("name")
                        ->label(__("Product Name"))
                        ->required()
                        ->maxLength(200)
                        ->columnSpanFull(),
                    (new static)->getCodeField('code', __("Product Code"))
                        ->unique(
                            \App\Models\Product::class,
                            'code',
                            ignoreRecord: true,
                            modifyRuleUsing: function ($rule) {
                                // Get the company_id from the session
                                $companyId = session('selected_company_id');

                                // If there's a selected company, scope the uniqueness check to that company
                                if ($companyId && $companyId !== 'all') {
                                    $rule->where('company_id', $companyId);
                                }
                                // If no company is selected, the uniqueness check will apply to all records
                                // This ensures records are unique within their company
                                return $rule;
                            },
                        ),
                    Textarea::make("description")
                        ->label(__("Description"))
                        ->columnSpanFull()
                        ->maxLength(65535),
                    FileUpload::make("image")
                        ->label(__("Product Image"))
                        ->image()
                        ->disk("public")
                        ->directory("products")
                        ->maxSize(2048)
                        ->acceptedFileTypes([
                            "image/jpeg",
                            "image/png",
                            "image/jpg",
                            "image/webp",
                        ])
                        ->columnSpanFull(),
                    Select::make("product_group_id")
                        ->label(__("Product Group"))
                        ->relationship(
                            "productGroup",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload()
                        ->required(),
                    Select::make("unit_id")
                        ->label(__("Unit"))
                        ->relationship(
                            "unit",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload()
                        ->required(),
                    Select::make("product_type")
                        ->label(__("Product Type"))
                        ->options([
                            'good' => __('Goods'),
                            'service' => __('Service'),
                        ])
                        ->default('good')
                        ->required(),
                    Select::make("tax_id")
                        ->label(__("Tax"))
                        ->relationship(
                            "tax",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                $query->where('is_active', true);
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload(),
                    Select::make("company_id")
                        ->label(__("Company"))
                        ->relationship(
                            name: 'company',
                            titleAttribute: 'name',
                            modifyQueryUsing: function ($query) {
                                $user = auth()->user();
                                if ($user) {
                                    $userCompanyIds = $user->companies()->pluck('companies.id');
                                    if ($userCompanyIds->isNotEmpty()) {
                                        $query->whereIn('companies.id', $userCompanyIds);
                                    } else {
                                        // If user has no assigned companies, return no results
                                        $query->whereRaw('1 = 0');
                                    }
                                }
                            }
                        )
                        ->default(function () {
                            $selectedCompanyId = session("selected_company_id");
                            $user = auth()->user();
                            if ($selectedCompanyId) {
                                // Verify user has access to this company
                                if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                    return $selectedCompanyId;
                                }
                            }
                            return null;
                        })
                        ->hidden()
                        ->searchable()
                        ->preload()
                        ->required(),
                    Toggle::make("is_active")
                        ->label(__("Active"))
                        ->default(true),
                ])
                ->columns(2),

            Section::make(__("Pricing"))
                ->schema([
                    NumberInput::make("cost_price")
                        ->label(__("Cost Price"))
                        ->required()
                        ->minValue(0)
                        ->prefix('Rp')
                        ->default(0)
                        ->decimal(false),
                    NumberInput::make("selling_price")
                        ->label(__("Selling Price"))
                        ->required()
                        ->minValue(0)
                        ->prefix('Rp')
                        ->default(0)
                        ->decimal(false),
                ])
                ->columns(2),

            Section::make(__("Unit Conversions"))
                ->description(__("Define alternate units for this product. Conversion factor = how many base units equal 1 of this unit."))
                ->schema([
                    Placeholder::make('base_unit_info')
                        ->label(__("Base Unit"))
                        ->content(function ($record) {
                            $unit = $record?->unit;
                            return $unit ? $unit->name : __('Not set');
                        }),
                    Repeater::make('productUnits')
                        ->relationship()
                        ->hiddenLabel()
                        ->addActionLabel(__('Add Alternate Unit'))
                        ->table([
                            TableColumn::make('Unit')->width('25%')->alignment(Alignment::Start),
                            TableColumn::make('Conversion Factor')->width('25%')->alignment(Alignment::End),
                            TableColumn::make('Purchase')->width('15%')->alignment(Alignment::Center),
                            TableColumn::make('Sales')->width('15%')->alignment(Alignment::Center),
                            TableColumn::make('Info')->width('20%')->alignment(Alignment::Start),
                        ])
                        ->schema([
                            Select::make('unit_id')
                                ->label(__('Unit'))
                                ->options(function (callable $get) {
                                    $selectedCompanyId = session('selected_company_id');
                                    $q = Unit::query();
                                    if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                        $q->where('company_id', $selectedCompanyId);
                                    }
                                    // Exclude the product's base unit from alternate unit options
                                    $baseUnitId = $get('../../unit_id');
                                    if ($baseUnitId) {
                                        $q->where('id', '!=', $baseUnitId);
                                    }
                                    return $q->orderBy('name')->pluck('name', 'id')->toArray();
                                })
                                ->searchable()
                                ->preload()
                                ->required(),
                            TextInput::make('conversion_factor')
                                ->label(__('Conversion Factor'))
                                ->required()
                                ->numeric()
                                ->default(1)
                                ->step(0.000001)
                                ->minValue(0.000001)
                                ->extraInputAttributes(['style' => 'text-align:right']),
                            Toggle::make('is_purchase_unit')
                                ->label(__('Purchase'))
                                ->default(true)
                                ->inline(false),
                            Toggle::make('is_sales_unit')
                                ->label(__('Sales'))
                                ->default(true)
                                ->inline(false),
                            Placeholder::make('conversion_info')
                                ->label(__('Info'))
                                ->content(function (callable $get) {
                                    $factor = $get('conversion_factor');
                                    $unitId = $get('unit_id');
                                    if (!$factor || !$unitId) {
                                        return '-';
                                    }
                                    $unit = Unit::find($unitId);
                                    $productName = $get('../../name') ?? 'product';
                                    $baseUnitId = $get('../../unit_id');
                                    $baseUnit = $baseUnitId ? Unit::find($baseUnitId) : null;
                                    $baseName = $baseUnit?->name ?? 'base unit';
                                    return '1 ' . ($unit?->name ?? 'unit') . ' = ' . rtrim(rtrim(number_format((float) $factor, 6), '0'), '.') . ' ' . $baseName;
                                }),
                        ])
                        ->defaultItems(0)
                        ->reorderable(false)
                        ->collapsible()
                        ->compact()
                        ->columnSpanFull(),
                ])
                ->collapsible()
                ->collapsed(false),
        ]);
    }
}
