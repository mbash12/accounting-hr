<?php

namespace App\Filament\Resources\Products\Schemas;

use App\Traits\HasAutoGeneratedCode;
use Filament\Actions\Action;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\RawJs;

class ProductForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for products
     */
    protected function getDocumentType(): string
    {
        return 'product';
    }

    /**
     * Get the code field name for products
     */
    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__("Informasi Produk"))
                ->schema([
                    TextInput::make("name")
                        ->label(__("Nama Produk"))
                        ->required()
                        ->maxLength(200)
                        ->columnSpanFull(),
                    (new static)->getCodeField('code', __("Kode Produk"))
                        ->unique(
                            \App\Models\Product::class,
                            'code',
                            ignoreRecord: true,
                            modifyRuleUsing: function ($rule) {
                                // Get the company_id from the session
                                $companyId = session('selected_company_id');

                                // If there's a selected company, scope the uniqueness check to that company
                                if ($companyId && $companyId !== 'all') {
                                    $rule->where('company_id', $companyId);
                                }
                                // If no company is selected, the uniqueness check will apply to all records
                                // This ensures records are unique within their company
                                return $rule;
                            },
                        ),
                    Textarea::make("description")
                        ->label(__("Deskripsi"))
                        ->columnSpanFull()
                        ->maxLength(65535),
                    FileUpload::make("image")
                        ->label(__("Gambar Produk"))
                        ->image()
                        ->disk("public")
                        ->directory("products")
                        ->maxSize(2048)
                        ->acceptedFileTypes([
                            "image/jpeg",
                            "image/png",
                            "image/jpg",
                            "image/webp",
                        ])
                        ->columnSpanFull(),
                    Select::make("product_group_id")
                        ->label(__("Kelompok Produk"))
                        ->relationship(
                            "productGroup",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload()
                        ->required(),
                    Select::make("unit_id")
                        ->label(__("Satuan"))
                        ->relationship(
                            "unit",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload()
                        ->required(),
                    Select::make("product_type")
                        ->label(__("Jenis Produk"))
                        ->options([
                            'good' => __('Barang'),
                            'service' => __('Jasa'),
                        ])
                        ->default('good')
                        ->required(),
                    Select::make("tax_id")
                        ->label(__("Pajak"))
                        ->relationship(
                            "tax",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                $query->where('is_active', true);
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload(),
                    Select::make("company_id")
                        ->label(__("Perusahaan"))
                        ->relationship(
                            name: 'company',
                            titleAttribute: 'name',
                            modifyQueryUsing: function ($query) {
                                $user = auth()->user();
                                if ($user) {
                                    $userCompanyIds = $user->companies()->pluck('companies.id');
                                    if ($userCompanyIds->isNotEmpty()) {
                                        $query->whereIn('companies.id', $userCompanyIds);
                                    } else {
                                        // If user has no assigned companies, return no results
                                        $query->whereRaw('1 = 0');
                                    }
                                }
                            }
                        )
                        ->default(function () {
                            $selectedCompanyId = session("selected_company_id");
                            $user = auth()->user();
                            if ($selectedCompanyId) {
                                // Verify user has access to this company
                                if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                    return $selectedCompanyId;
                                }
                            }
                            return null;
                        })
                        ->hidden()
                        ->searchable()
                        ->preload()
                        ->required(),
                    Toggle::make("is_active")
                        ->label(__("Aktif"))
                        ->default(true),
                ])
                ->columns(2),

            Section::make(__("Harga & Pemasok"))
                ->schema([
                    TextInput::make("cost_price")
                        ->label(__("Harga Pokok"))
                        ->required()
                        ->numeric()
                        ->minValue(0)
                        ->prefix('Rp')
                        ->default(0)
                        ->mask(RawJs::make('$money($input, \',\', \'.\')'))
                        ->stripCharacters('.'),
                    TextInput::make("selling_price")
                        ->label(__("Harga Jual"))
                        ->required()
                        ->numeric()
                        ->minValue(0)
                        ->prefix('Rp')
                        ->default(0)
                        ->mask(RawJs::make('$money($input, \',\', \'.\')'))
                        ->stripCharacters('.'),
                    Select::make("supplier_id")
                        ->label(__("Pemasok"))
                        ->relationship(
                            "supplier",
                            "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where('company_id', $selectedCompanyId);
                                }
                                $query->where('is_supplier', true);
                                return $query;
                            }
                        )
                        ->searchable()
                        ->preload(),
                    TextInput::make("min_order_qty")
                        ->label(__("Jumlah Minimum Pesanan"))
                        ->numeric()
                        ->helperText(__("Biarkan kosong jika tidak ada jumlah minimum pesanan"))
                        ->default(0)
                        ->mask(RawJs::make('$money($input, \',\', \'.\')'))
                        ->stripCharacters('.'),
                ])
                ->columns(2),
        ]);
    }
}
