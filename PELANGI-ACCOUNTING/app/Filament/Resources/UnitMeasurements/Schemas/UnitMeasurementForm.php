<?php

namespace App\Filament\Resources\UnitMeasurements\Schemas;

use App\Models\UnitCategory;
use Filament\Forms\Components\Placeholder;
use App\Models\Unit;
use App\Traits\HasAutoGeneratedCode;
use Filament\Actions\Action;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

class UnitMeasurementForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for unit measurements
     */
    protected function getDocumentType(): string
    {
        return 'unit_measurement';
    }

    /**
     * Get the code field name for unit measurements
     */
    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make('Unit Measurement Information')
                    ->schema([
                        (new static)->getCodeField('code', __('Unit Measurement Code'))
                            ->rule('required')
                            ->rule(function (?Unit $record) {
                                return function (string $attribute, $value, \Closure $fail) use ($record) {
                                    $query = Unit::where('code', $value);

                                    if ($record && $record->id) {
                                        // Editing: exclude current record
                                        $query->where('id', '!=', $record->id);
                                    }

                                    // Scope to the same company
                                    if ($record && $record->company_id) {
                                        $query->where('company_id', $record->company_id);
                                    } else {
                                        $companyId = session('selected_company_id') ?? auth()->user()->companies()->first()?->id;
                                        $query->where('company_id', $companyId);
                                    }

                                    if ($query->exists()) {
                                        $fail(__('The :attribute has already been taken.'));
                                    }
                                };
                            })
                            ->disabled(),
                        TextInput::make('name')
                            ->disabled()
                            ->required()
                            ->label(__('Unit Measurement Name')),
                        Textarea::make('description')
                            ->disabled()
                            ->label(__('Description')),
                        Toggle::make('is_active')
                            ->disabled()
                            ->required()
                            ->label(__('Active'))->default(true),
                        Select::make('unit_category_id')
                            ->disabled()
                            ->label(__('UOM Category'))
                            ->options(function () {
                                $selectedCompanyId = session('selected_company_id');
                                $q = UnitCategory::query()->with('baseUnit');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $q->where('company_id', $selectedCompanyId);
                                }
                                return $q->orderBy('name')->get()
                                    ->mapWithKeys(fn ($c) => [$c->id => $c->name . ' (base: ' . $c->baseUnit->name . ')'])
                                    ->toArray();
                            })
                            ->searchable()
                            ->preload()
                            ->nullable()
                            ->live()
                            ->hint(__('Optional — assign to a category for global conversions')),
                        TextInput::make('conversion_factor')
                            ->label(__('Conversion Factor'))
                            ->required()
                            ->numeric()
                            ->default(1)
                            ->step(0.000001)
                            ->minValue(0.000001)
                            ->live()
                            ->disabled()
                            ->hint(function (callable $get, ?Unit $record) {
                                $categoryId = $get('unit_category_id');
                                if (!$categoryId || !$record) return __('1 of this unit = X of the category base unit');
                                $category = UnitCategory::find($categoryId);
                                if ($category && $category->base_unit_id === $record->id) {
                                    return __('This unit is the category base — factor is always 1');
                                }
                                return __('1 of this unit = X of the category base unit');
                            })
                            ->extraInputAttributes(['style' => 'text-align:right']),
                        Placeholder::make('conversion_preview')
                            ->label(__(''))
                            ->content(function (callable $get) {
                                $categoryId = $get('unit_category_id');
                                $factor = (float) ($get('conversion_factor') ?? 1);
                                if (!$categoryId) return '-';
                                $category = UnitCategory::with('baseUnit')->find($categoryId);
                                if (!$category) return '-';
                                $unitName = $get('name') ?: 'this unit';
                                $baseName = $category->baseUnit->name;
                                return '1 ' . $unitName . ' = ' . rtrim(rtrim(number_format($factor, 6), '0'), '.') . ' ' . $baseName;
                            }),
                        Select::make('company_id')
                            ->relationship(
                                name: 'company',
                                titleAttribute: 'name',
                                modifyQueryUsing: function ($query) {
                                    $user = auth()->user();
                                    if ($user) {
                                        $userCompanyIds = $user->companies()->pluck('companies.id');
                                        if ($userCompanyIds->isNotEmpty()) {
                                            $query->whereIn('companies.id', $userCompanyIds);
                                        } else {
                                            // If user has no assigned companies, return no results
                                            $query->whereRaw('1 = 0');
                                        }
                                    }
                                }
                            )
                            ->default(function () {
                                $selectedCompanyId = session('selected_company_id');
                                $user = auth()->user();
                                if ($selectedCompanyId) {
                                    // Verify user has access to this company
                                    if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                        return $selectedCompanyId;
                                    }
                                }
                                return null;
                            })
                            ->hidden()
                            ->searchable()
                            ->preload()
                            ->required()
                            ->label(__('Company')),
                        Select::make('created_by_user_id')
                            ->relationship('createdByUser', 'name')
                            ->default(fn () => auth()->id())
                            ->disabled()
                            ->hidden()
                            ->required()
                            ->label(__('Created By')),
                    ])
                    ->columns(2)
                    ->columnSpanFull(),
            ]);
    }
}
