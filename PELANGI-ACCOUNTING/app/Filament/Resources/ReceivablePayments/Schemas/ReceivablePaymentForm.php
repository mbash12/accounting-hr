<?php

namespace App\Filament\Resources\ReceivablePayments\Schemas;

use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Hidden;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Repeater\TableColumn;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Forms\Components\Checkbox;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Enums\Alignment;
use App\Filament\Forms\Components\NumberInput;
use App\Filament\Forms\Components\RoundedIntegerMoneyInput;

class ReceivablePaymentForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for code generation
     *
     * @return string
     */
    protected function getDocumentType(): string
    {
        return 'receivable_payment';
    }

    /**
     * Get code field name
     *
     * @return string
     */
    protected function getCodeFieldName(): string
    {
        return 'payment_number';
    }

    public static function refreshTotal($get, $set): void
    {
        $items = $get('items') ?? [];
        $totalItems = 0;
        foreach ($items as $item) {
            $totalItems += \App\Filament\Forms\Components\NumberInput::parseToFloat($item['set_payment'] ?? 0);
        }

        $otherCosts = \App\Filament\Forms\Components\NumberInput::parseToFloat($get('other_costs') ?? 0);

        $set('total_payment', $totalItems + $otherCosts);
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            (new static)->getCodeField('payment_number', __('Nomor Pembayaran')),
            Select::make("company_id")
                ->label(__("Perusahaan"))
                ->relationship("company", "name")
                ->default(function () {
                    $selectedCompanyId = session("selected_company_id");
                    if (
                        $selectedCompanyId &&
                        $selectedCompanyId !== "all"
                    ) {
                        return $selectedCompanyId;
                    }
                    return null;
                })
                ->hidden(function () {
                    $selectedCompanyId = session("selected_company_id");
                    return $selectedCompanyId &&
                        $selectedCompanyId !== "all";
                })
                ->required(function () {
                    $selectedCompanyId = session("selected_company_id");
                    return !(
                        $selectedCompanyId &&
                        $selectedCompanyId === "all"
                    );
                })
                ->searchable()
                ->preload()
                ->columnSpanFull(),
            
            Section::make()
                ->schema([
                    Select::make("customer_id")
                        ->label(__("Pelanggan"))
                        ->relationship(
                            name: "customer",
                            titleAttribute: "name",
                            modifyQueryUsing: function ($query) {
                                $selectedCompanyId = session("selected_company_id");
                                if ($selectedCompanyId && $selectedCompanyId !== "all") {
                                    $query->where("company_id", $selectedCompanyId);
                                }
                                return $query->where('is_customer', true)->orderBy('name');
                            }
                        )
                        ->getOptionLabelFromRecordUsing(fn ($record) => "{$record->name} ({$record->contact_code})")
                        ->searchable(['name', 'contact_code'])
                        ->preload()
                        ->required()
                        ->live(onBlur: false)
                        ->afterStateUpdated(function ($state, $set, $get) {
                            // Clear items when customer changes
                            $set('items', []);
                            
                            // Tambahkan 1 item baru setelah customer dipilih
                            if ($state) {
                                $set('items', [[
                                    'sales_invoice_id' => null,
                                    'date' => null,
                                    'amount' => 0,
                                    'paid_amount' => 0,
                                    'discount_amount' => 0,
                                    'set_payment' => 0,
                                ]]);
                                
                                \Log::info('🔄 Customer berubah - Item baru ditambahkan', [
                                    'customer_id_baru' => $state,
                                    'items_count' => 1,
                                ]);
                            } else {
                                \Log::info('🔄 Customer dihapus - Items dibersihkan', [
                                    'items_count' => 0,
                                ]);
                            }
                        })
                        ->columnSpan(1),
                    DatePicker::make("payment_date")
                        ->label(__("Tanggal Pembayaran"))
                        ->required()
                        ->default(now())
                        ->columnSpan(1),
                    TextInput::make("reference_no")
                        ->maxLength(255)
                        ->label(__("Nomor Referensi"))
                        ->columnSpan(1),
                    Select::make("bank_account_id")
                        ->label(__("Akun"))
                        ->options(function () {
                            $selectedCompanyId = session('selected_company_id');
                            $query = \App\Models\Account::where('is_header', false)
                                ->where('is_active', true)
                                ->where('is_cash_bank', true);

                            if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                $query->where(function ($q) use ($selectedCompanyId) {
                                    $q->where('company_id', $selectedCompanyId)
                                        ->orWhereNull('company_id');
                                });
                            }

                            return $query->orderBy('code')
                                ->limit(100)
                                ->get()
                                ->mapWithKeys(fn ($account) => [
                                    $account->id => "{$account->code} - {$account->name}",
                                ]);
                        })
                        ->searchable()
                        ->preload()
                        ->required()
                        ->columnSpan(1),
                    Checkbox::make("is_incoming_giro")
                        ->label(__("Giro Masuk"))
                        ->default(false)
                        ->columnSpan(1),
                    Textarea::make("description")
                        ->rows(2)
                        ->maxLength(65535)
                        ->label(__("Keterangan"))
                        ->columnSpan(1),
                ])
                ->columns(3)
                ->columnSpanFull(),

            // Item Pembayaran
            Repeater::make("items")
                ->label(__("Item Pembayaran"))
                ->addActionLabel(__("Tambah Faktur"))
                ->defaultItems(1)
                ->live()
                ->afterStateUpdated(function ($set, $get) {
                    static::refreshTotal($get, $set);
                })
                ->schema([
                    Select::make("sales_invoice_id")
                        ->label(__("Nomor Faktur"))
                        ->options(function ($get, $record) {
                            $customerId = $get('../../customer_id') 
                                ?? $get('../customer_id') 
                                ?? $get('customer_id')
                                ?? ($record?->customer_id ?? null);
                            
                            if (!$customerId) {
                                return [];
                            }
                            
                            $selectedCompanyId = session('selected_company_id');
                            
                            $currentInvoiceId = $get('sales_invoice_id');
                            
                            $invoiceIds = [];
                            if ($record && $record->exists) {
                                try {
                                    $items = $record->items()->get();
                                    if ($items && $items->count() > 0) {
                                        $invoiceIds = $items->pluck('sales_invoice_id')->filter()->unique()->toArray();
                                    }
                                } catch (\Exception $e) {
                                    $items = $record->items ?? [];
                                    if (is_array($items) && count($items) > 0) {
                                        $invoiceIds = collect($items)->pluck('sales_invoice_id')->filter()->unique()->toArray();
                                    }
                                }
                            }
                            
                            $allInvoiceIds = array_filter(array_merge([$currentInvoiceId], $invoiceIds));
                            
                            $query = \App\Models\SalesInvoice::where('customer_id', $customerId)
                                ->whereIn('status', ['posted', 'sent', 'overdue', 'partially_paid', 'paid']);

                            if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                $query->where(function ($q) use ($selectedCompanyId) {
                                    $q->where('company_id', $selectedCompanyId)
                                        ->orWhereNull('company_id');
                                });
                            }

                            $query->where(function ($q) use ($allInvoiceIds) {
                                $q->where(function ($subQ) {
                                    $subQ->where('outstanding_amount', '>', 0)
                                        ->orWhere('is_paid', false);
                                });
                                
                                if (!empty($allInvoiceIds)) {
                                    $q->orWhereIn('id', $allInvoiceIds);
                                }
                            });

                            $invoices = $query->orderBy('date', 'desc')
                                ->limit(100)
                                ->get();

                            return $invoices->mapWithKeys(fn ($invoice) => [
                                $invoice->id => $invoice->invoice_number . ' - ' . 
                                    number_format((float) $invoice->outstanding_amount, 0, ',', '.') . ' IDR',
                            ]);
                        })
                        ->getSearchResultsUsing(function (string $search, $get, $record) {
                            $customerId = $get('../../customer_id') 
                                ?? $get('../customer_id') 
                                ?? $get('customer_id')
                                ?? ($record?->customer_id ?? null);
                            
                            if (!$customerId) {
                                return [];
                            }

                            $selectedCompanyId = session('selected_company_id');
                            
                            $currentInvoiceId = $get('sales_invoice_id');
                            
                            $invoiceIds = [];
                            if ($record && $record->exists) {
                                try {
                                    $items = $record->items()->get();
                                    if ($items && $items->count() > 0) {
                                        $invoiceIds = $items->pluck('sales_invoice_id')->filter()->unique()->toArray();
                                    }
                                } catch (\Exception $e) {
                                    $items = $record->items ?? [];
                                    if (is_array($items) && count($items) > 0) {
                                        $invoiceIds = collect($items)->pluck('sales_invoice_id')->filter()->unique()->toArray();
                                    }
                                }
                            }
                            
                            $allInvoiceIds = array_filter(array_merge([$currentInvoiceId], $invoiceIds));
                            
                            $query = \App\Models\SalesInvoice::where('customer_id', $customerId)
                                ->whereIn('status', ['draft', 'sent', 'overdue', 'partially_paid', 'paid'])
                                ->where(function ($q) use ($search) {
                                    $q->where('invoice_number', 'like', "%{$search}%");
                                });

                            if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                $query->where(function ($q) use ($selectedCompanyId) {
                                    $q->where('company_id', $selectedCompanyId)
                                        ->orWhereNull('company_id');
                                });
                            }

                            $query->where(function ($q) use ($allInvoiceIds) {
                                $q->where(function ($subQ) {
                                    $subQ->where('outstanding_amount', '>', 0)
                                        ->orWhere('is_paid', false);
                                });
                                
                                if (!empty($allInvoiceIds)) {
                                    $q->orWhereIn('id', $allInvoiceIds);
                                }
                            });

                            return $query->orderBy('date', 'desc')
                                ->limit(50)
                                ->get()
                                ->mapWithKeys(fn ($invoice) => [
                                    $invoice->id => $invoice->invoice_number . ' - ' . 
                                        number_format((float) $invoice->outstanding_amount, 0, ',', '.') . ' IDR',
                                ]);
                        })
                        ->searchable()
                        ->preload()
                        ->required()
                        ->default(null)
                        ->live()
                        ->rules([
                            function ($get) {
                                return function (string $attribute, $value, \Closure $fail) use ($get) {
                                    if (!$value) {
                                        return;
                                    }
                                    
                                    $items = $get('../../items') ?? [];
                                    if (!is_array($items)) {
                                        return;
                                    }
                                    
                                    $currentIndex = null;
                                    if (preg_match('/items\.(\d+)\.sales_invoice_id/', $attribute, $matches)) {
                                        $currentIndex = (int) $matches[1];
                                    }
                                    
                                    $duplicates = [];
                                    foreach ($items as $index => $item) {
                                        if (!is_array($item)) {
                                            continue;
                                        }
                                        
                                        $itemIndex = is_numeric($index) ? (int) $index : null;
                                        
                                        if ($itemIndex !== null && $itemIndex !== $currentIndex && isset($item['sales_invoice_id']) && $item['sales_invoice_id'] == $value) {
                                            $duplicates[] = $itemIndex + 1;
                                        }
                                    }
                                    
                                    if (!empty($duplicates)) {
                                        $fail(__('Nomor faktur tidak boleh sama. Faktur ini sudah digunakan pada item :items.', [
                                            'items' => implode(', ', $duplicates)
                                        ]));
                                    }
                                };
                            },
                        ])
                        ->disabled(function ($get, $record) {
                            $customerId = $get('../../customer_id') 
                                ?? $get('../customer_id') 
                                ?? $get('customer_id')
                                ?? ($record?->customer_id ?? null);
                            return !$customerId;
                        })
                        ->getOptionLabelUsing(function ($value) {
                            if (!$value) {
                                return null;
                            }
                            $invoice = \App\Models\SalesInvoice::find($value);
                            if ($invoice) {
                                return $invoice->invoice_number . ' - ' . 
                                    number_format((float) $invoice->outstanding_amount, 0, ',', '.') . ' IDR';
                            }
                            return null;
                        })
                        ->dehydrated(true)
                        ->afterStateUpdated(function ($state, callable $set, callable $get) {
                            if ($state) {
                                $invoice = \App\Models\SalesInvoice::find($state);
                                if ($invoice) {
                                    // Set date
                                    if ($invoice->date) {
                                        if ($invoice->date instanceof \Carbon\Carbon) {
                                            $dateValue = $invoice->date->format('Y-m-d');
                                        } elseif (is_string($invoice->date)) {
                                            $dateValue = $invoice->date;
                                        } else {
                                            try {
                                                $dateValue = \Carbon\Carbon::parse($invoice->date)->format('Y-m-d');
                                            } catch (\Exception $e) {
                                                $dateValue = null;
                                            }
                                        }
                                        $set('date', $dateValue);
                                    } else {
                                        $set('date', null);
                                    }
                                    
                                    $outstandingAmount = (float) ($invoice->outstanding_amount ?? 0);
                                    $set('amount', $outstandingAmount);
                                    $set('amount_display', \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay($outstandingAmount));
                                    
                                    $paidAmount = (float) ($invoice->paid_amount ?? 0);
                                    $set('paid_amount', $paidAmount);
                                    $set('discount_amount', 0);
                                    
                                    $setPayment = max(0, $outstandingAmount);
                                    $set('set_payment', $setPayment);
                                    $set('set_payment_display', \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay($setPayment, 0));
                                    
                                    static::refreshTotal($get, $set);
                                } else {
                                    $set('date', null);
                                    $set('amount', 0);
                                    $set('amount_display', '0');
                                    $set('set_payment', 0);
                                    $set('set_payment_display', '0');
                                }
                            } else {
                                $set('date', null);
                                $set('amount', 0);
                                $set('amount_display', '0');
                                $set('discount_amount', 0);
                                $set('set_payment', 0);
                                $set('set_payment_display', '0');

                                static::refreshTotal($get, $set);
                            }
                        }),
                    DatePicker::make("date")
                        ->label(__("Tanggal"))
                        ->disabled()
                        ->dehydrated(true)
                        ->displayFormat('d/m/Y')
                        ->native(false)
                        ->default(null)
                        ->extraInputAttributes(['style' => 'background-color: #f3f4f6; color: #6b7280;']),
                    ...RoundedIntegerMoneyInput::schema(
                        name: 'amount',
                        label: __('Jumlah'),
                        required: false,
                        extraInputAttributes: ['disabled' => true, 'style' => 'text-align:right; background-color: #f3f4f6; color: #6b7280;'],
                    ),
                    NumberInput::make("paid_amount")
                        ->label(__("Jumlah Dibayar"))
                        ->decimal(true)
                        ->default(0)
                        ->disabled()
                        ->dehydrated(true)
                        ->hidden()
                        ->extraInputAttributes(["style" => "text-align:right"]),
                    NumberInput::make("discount_amount")
                        ->label(__("Diskon"))
                        ->decimal(true)
                        ->default(0)
                        ->dehydrated(true)
                        ->suffix('%')
                        ->live()
                        ->afterStateUpdated(function ($set, $get) {
                            $salesInvoiceId = $get('sales_invoice_id');
                            if ($salesInvoiceId) {
                                $invoice = \App\Models\SalesInvoice::find($salesInvoiceId);
                                if ($invoice) {
                                    $outstandingAmount = (float) ($invoice->outstanding_amount ?? 0);
                                    $discountPercent = $get('discount_amount') ?? 0;
                                    $discountAmount = ($outstandingAmount * $discountPercent) / 100;
                                    $setPayment = $outstandingAmount - $discountAmount;
                                    $set('set_payment', max(0, $setPayment));
                                    $set('set_payment_display', \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay(max(0, $setPayment), 0));
                                }
                            } else {
                                $amount = $get('amount') ?? 0;
                                $paidAmount = $get('paid_amount') ?? 0;
                                $discountPercent = $get('discount_amount') ?? 0;
                                $outstandingAmount = $amount - $paidAmount;
                                $discountAmount = ($outstandingAmount * $discountPercent) / 100;
                                $setPayment = $outstandingAmount - $discountAmount;
                                $set('set_payment', max(0, $setPayment));
                                $set('set_payment_display', \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay(max(0, $setPayment), 0));
                            }
                            
                            static::refreshTotal($get, $set);
                        })
                        ->extraInputAttributes(["style" => "text-align:right"]),
                    ...RoundedIntegerMoneyInput::schema(
                        name: 'set_payment',
                        label: __('Nilai Pembayaran'),
                        required: true,
                        inlineLabel: false,
                        // scale: 0,
                        afterUpdated: function ($decimal, callable $set, callable $get) {
                            static::refreshTotal($get, $set);

                        },
                        extraInputAttributes: ["style" => "text-align:right"],
                        rules: [
                            function ($get) {
                                return function (string $attribute, $value, \Closure $fail) use ($get) {
                                    if (!$value) return;
                                    
                                    $amount = (float) ($get('amount') ?? 0);
                                    $payment = \App\Filament\Forms\Components\NumberInput::parseToFloat($value);
                                    
                                    if ($payment > $amount + 0.01) {
                                        $fail(__('Nilai pembayaran tidak boleh melebihi jumlah piutang (:amount).', [
                                            'amount' => \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay($amount)
                                        ]));
                                    }
                                };
                            }
                        ],
                    ),
                ])
                ->columns(5)
                ->reorderable()
                ->cloneable()
                ->collapsible()
                ->compact()
                ->columnSpan("full"),

            Section::make()
                ->schema([
                    Textarea::make("transaction_notes")
                        ->label(__("Catatan Transaksi"))
                        ->rows(5)
                        ->maxLength(1000)
                        ->placeholder(__("Tulis catatan transaksi di sini (maksimal 1000 karakter)"))
                        ->columnSpan(1),
                    Section::make()
                        ->schema([
                            Placeholder::make('empty_col_1')
                                ->hiddenLabel()
                                ->columnSpan(1),
                            ...RoundedIntegerMoneyInput::schema(
                                name: 'other_costs',
                                label: __('Biaya Lainnya'),
                                inlineLabel: true,
                                defaultDecimal: '0.00',
                                columnSpan: 2,
                                afterUpdated: function ($state, $set, $get) {
                                    static::refreshTotal($get, $set);
                                }
                            ),
                            Placeholder::make('empty_col_2')
                                ->hiddenLabel()
                                ->columnSpan(1),
                            Placeholder::make("total_payment_display")
                                ->inlineLabel()
                                ->label(__("Jumlah Total"))
                                ->live()
                                ->content(function ($get) {
                                    $items = $get('items') ?? [];
                                    $totalItems = 0;
                                    foreach ($items as $item) {
                                        $totalItems += \App\Filament\Forms\Components\NumberInput::parseToFloat($item['set_payment'] ?? 0);
                                    }

                                    $otherCosts = \App\Filament\Forms\Components\NumberInput::parseToFloat($get('other_costs') ?? 0);

                                    $total = $totalItems + $otherCosts;
                                    return 'Rp ' . \App\Filament\Forms\Components\NumberInput::formatRoundedIntegerDisplay($total);
                                })
                                ->extraAttributes([
                                    'class' => 'font-bold text-lg text-green-600'
                                ])
                                ->alignEnd()
                                ->columnSpan(2),
                        ])
                        ->columns(2)
                        ->columnSpan(1),
                ])
                ->columns(2)
                ->columnSpanFull(),

            Hidden::make("other_costs_account_id")
                ->default(function () {
                    $selectedCompanyId = session('selected_company_id');
                    
                    if (!$selectedCompanyId || $selectedCompanyId === 'all') {
                        return null;
                    }
                    
                    $mapping = \App\Models\AccountMapping::getAccountMapping(
                        'receivable_payment',
                        'other_costs',
                        $selectedCompanyId
                    );
                    
                    if ($mapping) {
                        return $mapping->id;
                    }
                    
                    $query = \App\Models\Account::where('is_header', false)
                        ->where('is_active', true)
                        ->where(function ($q) {
                            $q->where('code', 'like', '2102%')
                                ->orWhere('name', 'like', '%Uang Muka Penjualan%')
                                ->orWhere('name', 'like', '%Advance Sales%');
                        })
                        ->where(function ($q) use ($selectedCompanyId) {
                            $q->where('company_id', $selectedCompanyId)
                                ->orWhereNull('company_id');
                        });
                    
                    return $query->orderBy('code')->first()?->id;
                })
                ->dehydrated(true),

            Select::make("status")
                ->label(__("Status"))
                ->options([
                    'pending' => __('Menunggu'),
                    'completed' => __('Selesai'),
                    'failed' => __('Gagal'),
                    'cancelled' => __('Dibatalkan'),
                ])
                ->default('pending')
                ->required()
                ->hidden(),
            NumberInput::make("total_payment")
                ->label(__("Jumlah Total Pembayaran"))
                ->required()
                ->decimal(true)
                ->disabled()
                ->dehydrated(true)
                ->hidden()
                ->live()
                ->default(0),
        ]);
    }
}

