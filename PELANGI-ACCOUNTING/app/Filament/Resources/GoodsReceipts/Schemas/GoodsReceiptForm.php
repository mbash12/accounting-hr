<?php

namespace App\Filament\Resources\GoodsReceipts\Schemas;

use App\Filament\Forms\Components\NumberInput;
use App\Filament\Forms\Components\RoundedIntegerMoneyInput;
use App\Traits\HasAutoGeneratedCode;
use Filament\Actions\Action;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Repeater\TableColumn;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Enums\Alignment;
use Filament\Forms\Components\Hidden;


class GoodsReceiptForm
{
    use HasAutoGeneratedCode;

    /**
     * Get document type for goods receipts
     */
    protected function getDocumentType(): string
    {
        return 'goods_receipt';
    }

    /**
     * Get code field name for goods receipts
     */
    protected function getCodeFieldName(): string
    {
        return 'receipt_number';
    }

    protected static function resolveCompanyId(callable $get): ?int
    {
        $companyId = $get('company_id');
        if ($companyId && $companyId !== 'all') {
            return (int) $companyId;
        }
        $selectedCompanyId = session('selected_company_id');
        if ($selectedCompanyId && $selectedCompanyId !== 'all') {
            return (int) $selectedCompanyId;
        }
        return null;
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make()
                    ->schema([
                        Select::make('company_id')
                            ->relationship(
                                name: 'company',
                                titleAttribute: 'name',
                                modifyQueryUsing: function ($query) {
                                    $user = auth()->user();
                                    if ($user) {
                                        $userCompanyIds = $user->companies()->pluck('companies.id');
                                        if ($userCompanyIds->isNotEmpty()) {
                                            $query->whereIn('companies.id', $userCompanyIds);
                                        } else {
                                            // If user has no assigned companies, return no results
                                            $query->whereRaw('1 = 0');
                                        }
                                    }
                                }
                            )
                            ->default(function () {
                                $selectedCompanyId = session('selected_company_id');
                                return $selectedCompanyId && $selectedCompanyId !== 'all'
                                    ? $selectedCompanyId
                                    : null;
                            })
                            ->hidden(function () {
                                $selectedCompanyId = session('selected_company_id');
                                return $selectedCompanyId && $selectedCompanyId !== 'all';
                            })
                            ->searchable()
                            ->preload()
                            ->nullable()
                            ->columnSpanFull(),
                        Select::make('supplier_id')
                            ->label('Supplier')
                            ->disabled(fn ($record) => (bool) ($record?->is_locked))
                            ->relationship(
                                name: 'supplier',
                                titleAttribute: 'name',
                                modifyQueryUsing: function ($query, callable $get) {
                                    $companyId = self::resolveCompanyId($get);
                                    if ($companyId) {
                                        $query->where('company_id', $companyId);
                                    } else {
                                        $query->whereNull('company_id');
                                    }
                                    return $query->where('is_supplier', true)->orderBy('name');
                                }
                            )
                            ->getOptionLabelFromRecordUsing(fn ($record) => "{$record->name} ({$record->contact_code})")
                            ->searchable(['name', 'contact_code'])
                            ->preload()
                            ->live()
                            ->required()
                            ->afterStateUpdated(function ($state, callable $set) {
                                // Clear purchase order when supplier changes
                                $set('purchase_order_id', null);
                            })
                            ->createOptionForm([
                                TextInput::make('name')
                                    ->label(__('Name'))
                                    ->required(),
                                (new \App\Filament\Resources\Contacts\Schemas\ContactForm)->getCodeField('contact_code', __('Contact Code'))
                                    ->unique(\App\Models\Contact::class, 'contact_code', ignoreRecord: true,
                                        modifyRuleUsing: function ($rule) {
                                            // Get the company_id from the session
                                            $companyId = session('selected_company_id');

                                            // If there's a selected company, scope the uniqueness check to that company
                                            if ($companyId && $companyId !== 'all') {
                                                $rule->where('company_id', $companyId);
                                            }
                                            // If no company is selected, the uniqueness check will apply to all records
                                            // This ensures records are unique within their company
                                            return $rule;
                                        },
                                    ),
                                TextInput::make('email')
                                    ->label(__('Email'))
                                    ->email(),
                                TextInput::make('phone')
                                    ->label(__('Phone'))
                                    ->tel(),
                                Hidden::make('is_supplier')
                                    ->default(true),
                                Hidden::make('company_id')
                                    ->default(function (callable $get) {
                                        $companyId = $get('company_id') ?: session('selected_company_id');
                                        return ($companyId && $companyId !== 'all') ? $companyId : null;
                                    }),
                                Hidden::make('created_by_user_id')
                                    ->default(function () {
                                        return auth()->id();
                                    }),
                            ])
                            ->createOptionUsing(function (array $data) {
                                $contact = \App\Models\Contact::create($data);
                                return $contact->id;
                            }),
                        Select::make('purchase_order_id')
                            ->label('Purchase Order')
                            ->disabled(fn ($record) => (bool) ($record?->is_locked))
                            ->relationship(
                                name: 'purchaseOrder',
                                titleAttribute: 'purchase_order_no',
                                modifyQueryUsing: function ($query, callable $get) {
                                    $companyId = self::resolveCompanyId($get);
                                    if ($companyId) {
                                        $query->where('company_id', $companyId);
                                    } else {
                                        $query->whereNull('company_id');
                                    }

                                    $supplierId = $get('supplier_id');
                                    if ($supplierId) {
                                        $query->where('supplier_id', $supplierId);
                                    }

                                    // Only show purchase orders with 'approved' status
                                    $query->where('status', 'approved');

                                    // Only exclude POs that already have locked goods receipts when creating a new record
                                    // PO menu creates locked receipts automatically, so this prevents manual creation
                                    // if any receipt was created from PO menu
                                    $currentRecordId = $get('../../record')?->id ?? null;
                                    if (!$currentRecordId) {
                                        $query->whereDoesntHave('goodsReceipts', function ($receiptQuery) {
                                            $receiptQuery->where('is_locked', true)
                                                        ->whereNull('goods_receipts.deleted_at');
                                        });
                                    }

                                    return $query->orderBy('purchase_order_no', 'desc');
                                }
                            )
                            ->getOptionLabelFromRecordUsing(fn ($record) => "{$record->purchase_order_no} - " . ($record->supplier?->name ?? 'Unknown Supplier'))
                            ->searchable(['purchase_order_no'])
                            ->preload()
                            ->live(onBlur: true)
                            ->nullable()
                            ->afterStateUpdated(function ($state, callable $set, callable $get) {
                                if ($state) {
                                    $purchaseOrder = \App\Models\PurchaseOrder::with('items')->find($state);
                                    if ($purchaseOrder) {
                                        $set('supplier_id', $purchaseOrder->supplier_id);
                                        
                                        // Auto-populate items from PO
                                        if ($purchaseOrder->items) {
                                            $items = [];
                                            foreach ($purchaseOrder->items as $poItem) {
                                                $items[] = [
                                                    'purchase_order_item_id' => $poItem->id,
                                                    'product_id' => $poItem->product_id,
                                                    'quantity' => $poItem->quantity,
                                                    'quantity_display' => NumberInput::formatRoundedIntegerDisplay($poItem->quantity),
                                                    'description' => $poItem->description,
                                                    'unit_id' => $poItem->unit_id,
                                                    'conversion_factor' => $poItem->conversion_factor ?? 1,
                                                    'base_quantity' => $poItem->base_quantity ?? $poItem->quantity,
                                                ];
                                            }
                                            $set('items', $items);
                                        }
                                    }
                                }
                            }),
                        DatePicker::make('date')
                            ->label('Date')
                            ->required()
                            ->default(now()),
                        TextInput::make('reference_no')
                            ->maxLength(255)
                            ->label('Reference No.'),
                        (new static)->getCodeField('receipt_number', 'Receipt No.')
                            ->unique('goods_receipts', 'receipt_number', ignoreRecord: true,
                                modifyRuleUsing: fn ($rule) => $rule->where(function ($query) {
                                    $companyId = session('selected_company_id');
                                    if ($companyId && $companyId !== 'all') {
                                        $query->where('company_id', $companyId);
                                    } else {
                                        $query->whereNull('company_id');
                                    }
                                    $query->whereNull('deleted_at');
                                    return $query;
                                })
                            ),
                        Textarea::make('description')
                            ->rows(1)
                            ->maxLength(65535)
                            ->label(__('Description')),
                        Select::make('status')
                            ->label('Status')
                            ->options([
                                'draft' => 'Draft',
                            ])
                            ->default('draft')
                            ->required()
                            ->native(false)
                            ->disabled(fn ($record) => $record && $record->purchaseReturns()->exists())
                            ->live(),
                    ])
                    ->columns(3)
                    ->columnSpanFull(),

                // Goods Receipt Items
                Repeater::make('items')
                    ->relationship()
                    ->hiddenLabel()
                    ->addActionLabel(__('Add New Item'))
                    ->required()
                    ->addable(fn (callable $get) => !(bool) $get('is_locked'))
                    ->table([
                        TableColumn::make('Product')->width('35%')->alignment(Alignment::Start),
                        TableColumn::make('Quantity')->width('20%')->alignment(Alignment::End),
                        TableColumn::make('Unit')->width('15%')->alignment(Alignment::Start),
                        TableColumn::make('Description')->width('20%')->alignment(Alignment::Start),
                    ])
                    ->schema([
                        Hidden::make('purchase_order_item_id'),
                        Select::make('product_id')
                            ->required()
                            ->searchable()
                            ->preload()
                            ->label('Product')
                            ->disabled(fn (callable $get) => (bool) $get('../../is_locked'))
                            ->relationship(
                                name: 'product',
                                titleAttribute: 'name',
                                modifyQueryUsing: function ($query, callable $get) {
                                    $companyId = self::resolveCompanyId($get);
                                    if ($companyId) {
                                        $query->where('company_id', $companyId);
                                    } else {
                                        $query->whereNull('company_id');
                                    }
                                    return $query->orderBy('name');
                                }
                            )
                            ->getOptionLabelFromRecordUsing(fn ($record) => "{$record->name} ({$record->code})")
                            ->searchable(['name', 'code'])
                            ->preload()
                            ->live()
                            ->afterStateUpdated(function ($state, callable $set, callable $get) {
                                $product = \App\Models\Product::find($state);
                                if ($product) {
                                    if ($product->unit_id) {
                                        $set('unit_id', $product->unit_id);
                                        $set('conversion_factor', 1);
                                        $set('base_quantity', \App\Filament\Forms\Components\NumberInput::parseToFloat($get('quantity') ?? 0));
                                    }
                                    if ($product->description) {
                                        $set('description', $product->description);
                                    }
                                }
                            })
                            ->createOptionForm([
                                TextInput::make('name')
                                    ->label('Name')
                                    ->required(),
                                (new \App\Filament\Resources\Products\Schemas\ProductForm)->getCodeField('code', 'Product Code')
                                    ->unique(
                                        \App\Models\Product::class,
                                        'code',
                                        ignoreRecord: true,
                                        modifyRuleUsing: function ($rule) {
                                            $companyId = session('selected_company_id');
                                            if ($companyId && $companyId !== 'all') {
                                                $rule->where('company_id', $companyId);
                                            }
                                            return $rule;
                                        },
                                    ),
                                Select::make('product_group_id')
                                    ->label('Product Group')
                                    ->relationship(
                                        "productGroup",
                                        "name",
                                        modifyQueryUsing: function ($query) {
                                            $selectedCompanyId = session('selected_company_id');
                                            if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                                $query->where('company_id', $selectedCompanyId);
                                            }
                                            return $query;
                                        }
                                    )
                                    ->searchable()
                                    ->preload()
                                    ->required(),
                                ...RoundedIntegerMoneyInput::schema(
                                    name: 'cost_price',
                                    label: 'Cost Price',
                                    required: false,
                                    defaultDecimal: '0.00',
                                ),
                                Select::make('unit_id')
                                    ->label('Unit')
                                    ->searchable()
                                    ->options(function () {
                                        $selectedCompanyId = session('selected_company_id');
                                        $q = \App\Models\Unit::query();
                                        if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                            $q->where('company_id', $selectedCompanyId);
                                        } else {
                                            $q->whereNull('company_id');
                                        }
                                        return $q->orderBy('name')->pluck('name', 'id')->toArray();
                                    }),
                                Textarea::make('description')
                                    ->label('Description')
                                    ->rows(2),
                                Hidden::make('company_id')
                                    ->default(function () {
                                        $selectedCompanyId = session('selected_company_id');
                                        return ($selectedCompanyId && $selectedCompanyId !== 'all') ? $selectedCompanyId : null;
                                    }),
                                Hidden::make('created_by_user_id')
                                    ->default(function () {
                                        return auth()->id();
                                    }),
                            ])
                            ->createOptionUsing(function (array $data) {
                                $product = \App\Models\Product::create($data);
                                return $product->id;
                            }),
                        ...RoundedIntegerMoneyInput::schema(
                            name: 'quantity',
                            label: 'Quantity',
                            required: true,
                            defaultDecimal: '1.00',
                        ),
                        Select::make('unit_id')
                            ->searchable()
                            ->preload()
                            ->label('Unit')
                            ->required()
                            ->options(function (callable $get) {
                                $productId = $get('product_id');
                                if (!$productId) {
                                    return [];
                                }
                                $product = \App\Models\Product::find($productId);
                                if (!$product) {
                                    return [];
                                }
                                return app(\App\Services\UnitConversionService::class)->getUnitOptions($product, 'purchase');
                            })
                            ->live()
                            ->afterStateUpdated(function ($state, callable $set, callable $get) {
                                $productId = $get('product_id');
                                $quantity = \App\Filament\Forms\Components\NumberInput::parseToFloat($get('quantity') ?? 0);
                                if ($productId && $state) {
                                    $product = \App\Models\Product::find($productId);
                                    if ($product) {
                                        $factor = app(\App\Services\UnitConversionService::class)->getConversionFactor((int) $state, $product->unit_id);
                                        $set('conversion_factor', $factor);
                                        $set('base_quantity', $quantity * $factor);
                                    }
                                }
                            }),
                        Textarea::make('description')
                            ->label('Description')
                            ->rows(1),
                        Hidden::make('base_quantity')
                            ->default(0),
                        Hidden::make('conversion_factor')
                            ->default(1),
                    ])
                    ->defaultItems(0)
                    ->reorderable()
                    ->cloneable()
                    ->collapsible()
                    ->compact()
                    ->columnSpan('full'),

            ]);
    }
}