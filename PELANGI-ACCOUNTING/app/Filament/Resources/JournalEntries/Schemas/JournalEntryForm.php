<?php

namespace App\Filament\Resources\JournalEntries\Schemas;

use App\Traits\HasAutoGeneratedCode;
use App\Filament\Forms\Components\AccountSearchTable;
use App\Filament\Forms\Components\RoundedIntegerMoneyInput;
use App\Filament\Forms\Components\NumberInput;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Hidden;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Repeater\TableColumn;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Infolists\Components\TextEntry;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Enums\Alignment;
use Filament\Actions\Action;
use Filament\Tables\Table;
use Filament\Tables\Columns\TextColumn;
use Filament\Tables\Filters\SelectFilter;
use Filament\Tables\Actions\Action as TableAction;

class JournalEntryForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for code generation
     *
     * @return string
     */
    protected function getDocumentType(): string
    {
        return 'journal_entry';
    }

    /**
     * Get code field name
     *
     * @return string
     */
    protected function getCodeFieldName(): string
    {
        return 'entry_number';
    }

    protected static function calculateTotals(callable $get): array
    {
        $items = $get('items') ?? [];
        return self::calculateTotalsFromItems($items);
    }

    public static function calculateTotalsFromItems(array $items): array
    {
        $totalDebit = 0;
        $totalCredit = 0;
        
        foreach ($items as $item) {
            $itemArray = (array) $item;
            
            $debitValue = $itemArray['debit'] ?? $itemArray['debit_display'] ?? 0;
            $creditValue = $itemArray['credit'] ?? $itemArray['credit_display'] ?? 0;
            
            if (is_string($debitValue)) {
                $debitValue = NumberInput::parseToFloat($debitValue);
            }
            
            if (is_string($creditValue)) {
                $creditValue = NumberInput::parseToFloat($creditValue);
            }
            
            $totalDebit += (float) $debitValue;
            $totalCredit += (float) $creditValue;
        }
        
        $balance = $totalDebit - $totalCredit;
        
        return [
            'total_debit' => $totalDebit,
            'total_credit' => $totalCredit,
            'balance' => $balance,
        ];
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make()
                    ->schema([
                        (new static)->getCodeField(),
                        DatePicker::make('date')
                            ->required()
                            ->default(now()),
                        TextInput::make('reference_no')
                            ->maxLength(255)
                            ->label(__('Reference Number')),
                        Select::make('company_id')
                            ->relationship('company', 'name')
                            ->default(function () {
                                $selectedCompanyId = session('selected_company_id');
                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    return $selectedCompanyId;
                                }
                                return null; // Allow null for global records
                            })
                            ->hidden(function () {
                                $selectedCompanyId = session('selected_company_id');
                                return $selectedCompanyId && $selectedCompanyId !== 'all';
                            })
                            ->required(function () {
                                $selectedCompanyId = session('selected_company_id');
                                return !($selectedCompanyId && $selectedCompanyId === 'all');
                            })
                            ->searchable()
                            ->preload()
                            ->label(__('Company')),
                        Select::make('department_id')
                            ->relationship(
                                'department',
                                'name',
                                modifyQueryUsing: function ($query) {
                                    $selectedCompanyId = session('selected_company_id');
                                    if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                        $query->where(function ($q) use ($selectedCompanyId) {
                                            $q->where('company_id', $selectedCompanyId)
                                                ->orWhereNull('company_id');
                                        });
                                    }
                                }
                            )
                            ->searchable()
                            ->preload()
                            ->nullable()
                            ->label(__('Department')),
                        Textarea::make('description')
                            ->rows(2)
                            ->maxLength(65535)
                            ->label(__('Description'))
                            ->columnSpanFull(),
                    ])
                    ->columns(3)
                    ->columnSpanFull(),

                // Journal Entry Items (Debit/Credit)
                Repeater::make('items')
                    ->relationship('items')
                    ->hiddenLabel()
                    ->addActionLabel(__('Add Journal Item'))
                    ->live()
                    ->afterStateUpdated(function ($state, callable $set, callable $get) {
                        $totals = self::calculateTotals($get);
                        $set('total_debit_value', $totals['total_debit']);
                        $set('total_credit_value', $totals['total_credit']);
                        $set('calculated_balance', $totals['balance']);
                    })
                    ->rules([
                        fn (): \Closure => function (string $attribute, $value, \Closure $fail) {
                            $items = $value;
                            if (!is_array($items)) {
                                return;
                            }

                            $loopIndex = 0;
                            foreach ($items as $state) {
                                $loopIndex++;
                                $debit = $state['debit'] ?? '0.00';
                                $credit = $state['credit'] ?? '0.00';
                                
                                if (is_string($debit)) {
                                    $debit = NumberInput::parseToFloat($debit);
                                } else {
                                    $debit = (float) $debit;
                                }
                                
                                if (is_string($credit)) {
                                    $credit = NumberInput::parseToFloat($credit);
                                } else {
                                    $credit = (float) $credit;
                                }
                                
                                if ($debit <= 0 && $credit <= 0) {
                                    $fail(__('Item :index harus memiliki nilai debit atau kredit.', ['index' => $loopIndex]));
                                }
                                
                                if ($debit > 0 && $credit > 0) {
                                    $fail(__('Item :index tidak boleh memiliki nilai debit dan kredit sekaligus.', ['index' => $loopIndex]));
                                }
                            }
                        },
                    ])
                    ->table([
                        TableColumn::make('Akun')->width('25%')->alignment(Alignment::Start),
                        TableColumn::make('Deskripsi')->width('35%')->alignment(Alignment::Start),
                        TableColumn::make('Debit')->width('20%')->alignment(Alignment::End),
                        TableColumn::make('Kredit')->width('20%')->alignment(Alignment::End),
                    ])
                    ->schema([
                        Select::make('account_id')
                            ->required()
                            ->searchable()
                            ->preload()
                            ->label(__('Account'))
                            ->options(function ($get, $record) {
                                $selectedCompanyId = session('selected_company_id');
                                $companyId = $get('../../company_id') 
                                    ?? $get('../company_id') 
                                    ?? $get('company_id')
                                    ?? ($record?->company_id ?? null)
                                    ?? ($selectedCompanyId && $selectedCompanyId !== 'all' ? $selectedCompanyId : null);
                                

                                $query = \App\Models\Account::where('is_header', false)
                                    ->where('is_active', true);
                                
                                if ($companyId) {
                                    $query->where(function ($q) use ($companyId) {
                                        $q->where('company_id', $companyId);
                                    });
                                }
                                
                                return $query->orderBy('code')
                                    ->get()
                                    ->mapWithKeys(fn ($account) => [
                                        $account->id => "{$account->code} - {$account->name}",
                                    ]);
                            })
                            ->getSearchResultsUsing(function (string $search, $get, $record) {
                                $selectedCompanyId = session('selected_company_id');
                                $companyId = $get('../../company_id') 
                                    ?? $get('../company_id') 
                                    ?? $get('company_id')
                                    ?? ($record?->company_id ?? null)
                                    ?? ($selectedCompanyId && $selectedCompanyId !== 'all' ? $selectedCompanyId : null);
                                
                                $query = \App\Models\Account::where('is_header', false)
                                    ->where('is_active', true)
                                    ->where(function ($q) use ($search) {
                                        $q->whereRaw('LOWER(name) LIKE ?', ['%' . strtolower($search) . '%'])
                                            ->orWhereRaw('LOWER(code) LIKE ?', ['%' . strtolower($search) . '%']);
                                    });
                                
                                if ($companyId) {
                                    $query->where(function ($q) use ($companyId) {
                                        $q->where('company_id', $companyId);
                                    });
                                }
                                
                                return $query->orderBy('code')
                                    ->get()
                                    ->mapWithKeys(fn ($account) => [
                                        $account->id => "{$account->code} - {$account->name}",
                                    ]);
                            })
                            ->getOptionLabelUsing(function ($value) {
                                $account = \App\Models\Account::find($value);
                                return $account ? "{$account->code} - {$account->name}" : '';
                            }),
                        Textarea::make('notes')
                            ->label(__('Description'))
                            ->rows(1)
                            ->maxLength(65535),
                        ...RoundedIntegerMoneyInput::schema(
                            name: 'debit',
                            label: __('Debit'),
                            required: false,
                            defaultDecimal: '0.00',
                            afterUpdated: function ($decimal, callable $set, callable $get) {
                                $items = $get('../../items') ?? [];
                                $totals = self::calculateTotalsFromItems($items);
                                $set('../../total_debit_value', $totals['total_debit']);
                                $set('../../total_credit_value', $totals['total_credit']);
                                $set('../../calculated_balance', $totals['balance']);
                            },
                        ),
                        ...RoundedIntegerMoneyInput::schema(
                            name: 'credit',
                            label: __('Credit'),
                            required: false,
                            defaultDecimal: '0.00',
                            afterUpdated: function ($decimal, callable $set, callable $get) {
                                $items = $get('../../items') ?? [];
                                $totals = self::calculateTotalsFromItems($items);
                                $set('../../total_debit_value', $totals['total_debit']);
                                $set('../../total_credit_value', $totals['total_credit']);
                                $set('../../calculated_balance', $totals['balance']);
                            },
                        ),
                    ])
                    ->reorderable()
                    ->cloneable()
                    ->collapsible()
                    ->compact()
                    ->columnSpan('full'),

                Section::make()
                    ->schema([
                        Placeholder::make('empty_col_1')
                            ->hiddenLabel()
                            ->columnSpan(2),
                        Placeholder::make('total_debit')
                            ->label(__('TOTAL'))
                            ->content(function (callable $get) {
                                $items = $get('items') ?? [];
                                $totals = self::calculateTotalsFromItems($items);
                                return 'Rp ' . number_format($totals['total_debit'], 2, ',', '.');
                            })
                            ->live()
                            ->extraAttributes(['style' => 'text-align:right; font-weight: bold;'])
                            ->columnSpan(1),
                        Placeholder::make('total_credit')
                            ->label(__('TOTAL'))
                            ->content(function (callable $get) {
                                $items = $get('items') ?? [];
                                $totals = self::calculateTotalsFromItems($items);
                                return 'Rp ' . number_format($totals['total_credit'], 2, ',', '.');
                            })
                            ->live()
                            ->extraAttributes(['style' => 'text-align:right; font-weight: bold;'])
                            ->columnSpan(1),
                        Placeholder::make('empty_col_2')
                            ->hiddenLabel()
                            ->columnSpan(2),
                        Placeholder::make('balance')
                            ->label(__('SELISIH'))
                            ->content(function (callable $get) {
                                $items = $get('items') ?? [];
                                $totals = self::calculateTotalsFromItems($items);
                                $balance = $totals['balance'];
                                $isBalanced = abs($balance) < 0.01;
                                $color = $isBalanced ? 'text-green-600' : 'text-red-600';
                                $style = $isBalanced ? '' : 'color: #dc2626 !important;'; 
                                $formatted = number_format($balance, 2, ',', '.');
                                return '<span class="' . $color . ' font-bold" style="' . $style . '">Rp ' . $formatted . '</span>';
                            })
                            ->html()
                            ->live()
                            ->extraAttributes(['style' => 'text-align:right'])
                            ->columnSpan(1),
                        Placeholder::make('empty_col_3')
                            ->hiddenLabel()
                            ->columnSpan(1),
                        Hidden::make('total_debit_value')
                            ->default(0)
                            ->dehydrated(false)
                            ->live(),
                        Hidden::make('total_credit_value')
                            ->default(0)
                            ->dehydrated(false)
                            ->live(),
                        Hidden::make('calculated_balance')
                            ->default(0)
                            ->dehydrated(false)
                            ->live()
                            ->afterStateHydrated(function ($state, callable $set, callable $get) {
                                $totals = self::calculateTotals($get);
                                $set('total_debit_value', $totals['total_debit']);
                                $set('total_credit_value', $totals['total_credit']);
                                $set('calculated_balance', $totals['balance']);
                            }),
                        Hidden::make('amount')
                            ->default(0),
                        Hidden::make('total_amount')
                            ->default(0),
                        Hidden::make('sub_module')
                            ->default(null),
                        Hidden::make('reference_type')
                            ->default(null),
                        Hidden::make('reference_id')
                            ->default(null),
                        Hidden::make('status')
                            ->default('draft'),
                        Hidden::make('created_by_user_id')
                            ->default(auth()->id()),
                    ])
                    ->columns(4)
                    ->columnSpanFull(),

                Section::make(__('Entry Options'))
                    ->schema([
                        Toggle::make('is_posted')
                            ->label(__('Posted'))
                            // ->helperText(__('Mark this entry as posted to the ledger')),
                    ])
                    ->columns(2)
                    ->columnSpanFull(),

            ]);
    }
}