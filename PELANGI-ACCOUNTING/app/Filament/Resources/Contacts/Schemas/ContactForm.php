<?php

namespace App\Filament\Resources\Contacts\Schemas;

use App\Models\Company;
use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\FileUpload;
use Filament\Forms\Components\Hidden;
use Filament\Schemas\Components\Section;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Schema;

class ContactForm
{
    use HasAutoGeneratedCode;

    protected function getDocumentType(): string
    {
        return 'contact';
    }

    protected function getCodeFieldName(): string
    {
        return 'contact_code';
    }

    /**
     * Returns true when the currently selected company has PPN enabled.
     * NPWP/KTP is only mandatory for PPN companies.
     */
    protected static function isPpnCompany(): bool
    {
        $companyId = session('selected_company_id');

        if (! $companyId || $companyId === 'all') {
            return false;
        }

        $company = Company::find($companyId);

        return $company && (bool) $company->is_ppn;
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__("Contact Information"))
                ->schema([
                    TextInput::make("name")
                        ->label(__("Name"))
                        ->required()
                        ->maxLength(200)
                        ->columnSpanFull(),
                    ((new static)->getCodeField('contact_code', __('Contact Code')))
                        ->required(false)
                        ->maxLength(50)
                        ->unique(
                            \App\Models\Contact::class,
                            'contact_code',
                            ignoreRecord: true,
                            modifyRuleUsing: function ($rule) {
                                // Get the company_id from the form
                                $companyId = session('selected_company_id');
                                if ($companyId) {
                                    $rule->where('company_id', $companyId);
                                }
                                return $rule;
                            },
                        ),
                    TextInput::make("contact_person")
                        ->maxLength(200)
                        ->label(__("Contact Person")),
                    TextInput::make("email")
                        ->label(__("Email"))
                        ->email()
                        ->maxLength(150),
                    TextInput::make("phone")
                        ->label(__("Phone"))
                        ->tel()
                        ->maxLength(50),
                    Select::make("company_id")
                        ->label(__("Company"))
                        ->relationship(
                            name: 'company',
                            titleAttribute: 'name',
                            modifyQueryUsing: function ($query) {
                                $user = auth()->user();
                                if ($user) {
                                    $userCompanyIds = $user->companies()->pluck('companies.id');
                                    if ($userCompanyIds->isNotEmpty()) {
                                        $query->whereIn('companies.id', $userCompanyIds);
                                    } else {
                                        // If user has no assigned companies, return no results
                                        $query->whereRaw('1 = 0');
                                    }
                                }
                            }
                        )
                        ->default(function () {
                            $selectedCompanyId = session("selected_company_id");
                            $user = auth()->user();
                            if ($selectedCompanyId) {
                                // Verify user has access to this company
                                if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                    return $selectedCompanyId;
                                }
                            }
                            return null;
                        })
                        ->hidden()
                        ->searchable()
                        ->preload()
                        ->required(),
                    Toggle::make("is_active")
                        ->label(__("Active"))
                        ->required()
                        ->default(true),

                    // Contact Types moved here
                    Toggle::make("is_customer")
                        ->label(__("Customer"))
                        ->required()
                        ->default(true),
                    Toggle::make("is_supplier")
                        ->label(__("Supplier"))
                        ->required()
                        ->default(true),
                    Toggle::make("is_employee")
                        ->label(__("Employee"))
                        ->required()
                        ->default(true),
                    // Toggle::make("is_sales")
                    //     ->label(__("Sales Representative"))
                    //     ->required()
                    //     ->default(true),
                ])
                ->columns(2),

            Section::make(__("Address & Tax Information"))
                ->schema([
                    Textarea::make("billing_address_line_1")
                        ->label(__("Billing Address"))
                        ->columnSpanFull(),
                    // Hidden billing fields
                    Hidden::make("billing_address_line_2")->default(null),
                    Hidden::make("billing_city")->default(null),
                    Hidden::make("billing_state")->default(null),
                    Hidden::make("billing_postal_code")->default(null),
                    Hidden::make("billing_country")->default(null),

                    Textarea::make("delivery_address_line_1")
                        ->label(__("Delivery Address"))
                        ->columnSpanFull(),
                    // Hidden delivery fields
                    Hidden::make("delivery_address_line_2")->default(null),
                    Hidden::make("delivery_city")->default(null),
                    Hidden::make("delivery_state")->default(null),
                    Hidden::make("delivery_postal_code")->default(null),
                    Hidden::make("delivery_country")->default(null),

                    // Tax information moved here
                    TextInput::make("tax")
                        ->label(__("NPWP/KTP"))
                        ->maxLength(50),
                    Toggle::make("is_pkp")
                        ->label(__("PKP (Pengusaha Kena Pajak)"))
                        ->inline(false)
                        ->columnSpanFull(),
                    FileUpload::make("supporting_document")
                        ->label(__("NPWP/KTP Supporting Document"))
                        ->disk("public")
                        ->directory("contacts/supporting-documents")
                        ->acceptedFileTypes([
                            "application/pdf",
                            "image/jpeg",
                            "image/png",
                            "image/jpg",
                        ])
                        ->maxSize(5120),
                ])
                ->columns(2),
        ]);
    }
}
