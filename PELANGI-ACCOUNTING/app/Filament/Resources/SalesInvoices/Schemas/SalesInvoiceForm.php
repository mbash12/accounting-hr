                                if ($state) {
                                    $salesOrder = \App\Models\SalesOrder::with(['items.product', 'customer'])->find($state);
                                    if ($salesOrder) {
                                        $set('customer_id', $salesOrder->customer_id);

                                        // Auto-fill items from sales order
                                        $items = [];
