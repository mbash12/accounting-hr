                                    'draft' => 'Draft',
                                    'posted' => 'Posted',
                                    'sent' => 'Sent',
                                    'overdue' => 'Overdue',
                                    'paid' => 'Paid',
                                    'partially_paid' => 'Partially Paid',
                                    'written_off' => 'Written Off',
                                    'cancelled' => 'Cancelled',
                                ];
                            })
                            ->default('draft')
                            ->required()
