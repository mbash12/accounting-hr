                                // Recalculate due date when invoice date changes
                                $paymentTermId = $get('payment_term_id');
                                if ($paymentTermId) {
                                    $paymentTerm = \App\Models\PaymentTerm::find($paymentTermId);
                                    if ($paymentTerm && $state) {
                                        $dueDate = \Carbon\Carbon::parse($state)->addDays($paymentTerm->due_days);
