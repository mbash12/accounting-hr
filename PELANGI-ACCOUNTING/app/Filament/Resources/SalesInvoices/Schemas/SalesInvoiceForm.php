                            ->multiple()
                            ->directory('invoices')
                            ->maxFiles(20)
                            ->columnSpanFull()
                            ->disabled(fn ($record) => (bool) ($record?->is_locked)),
                        \Filament\Forms\Components\Hidden::make('total_amount')
                            ->default(0)
                            ->dehydrated(),
                        \Filament\Forms\Components\Hidden::make('outstanding_amount')
                            ->default(0)
                            ->dehydrated(),
                        \Filament\Forms\Components\Hidden::make('subtotal')
                            ->default(0)
                            ->dehydrated(),
                        \Filament\Forms\Components\Hidden::make('discount')
                            ->default(0)
                            ->dehydrated(),
                        \Filament\Forms\Components\Hidden::make('tax_amount')
                            ->default(0)
                            ->dehydrated(),
                        \Filament\Forms\Components\Hidden::make('paid_amount')
                            ->default(0)
                            ->dehydrated(),
                    ])
                    ->columns(3)
                    ->columnSpanFull(),

