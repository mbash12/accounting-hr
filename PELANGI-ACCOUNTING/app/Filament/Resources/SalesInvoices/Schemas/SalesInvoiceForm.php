                                } else {
                                    $set('due_date', null);
                                }
                            }),
                        DatePicker::make('due_date')
                            ->nullable()
                            ->label('Due Date')
                            ->disabled()
                            ->dehydrated(),
                        TextInput::make('reference_no')
                            ->maxLength(255)
                            ->label('Reference No'),
                        Textarea::make('description')
                            ->rows(1)
                            ->maxLength(65535)
                            ->label('Description'),
                        Select::make('status')
                            ->label('Status')
                            ->options(function ($get, $record) {
                                // If the record doesn't exist (creating new) or status is draft, show only draft/posted
                                if (!$record || $get('status') === 'draft') {
                                    return [
                                        'draft' => 'Draft',
                                    ];
