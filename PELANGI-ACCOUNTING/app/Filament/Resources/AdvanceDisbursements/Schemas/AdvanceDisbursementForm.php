<?php

namespace App\Filament\Resources\AdvanceDisbursements\Schemas;

use App\Traits\HasAutoGeneratedCode;
use App\Forms\Components\SelectWithModal;
use App\Filament\Forms\Components\NumberInput;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Placeholder;
use Filament\Forms\Components\Repeater;
use Filament\Forms\Components\Repeater\TableColumn;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\Enums\Alignment;


class AdvanceDisbursementForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for advance disbursements
     */
    protected function getDocumentType(): string
    {
        return 'advance_disbursement';
    }

    /**
     * Get the code field name for advance disbursements
     */
    protected function getCodeFieldName(): string
    {
        return 'advance_number';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make()
                    ->schema([
                        Select::make("company_id")
                            ->label(__("Company"))
                            ->relationship("company", "name")
                            ->default(function () {
                                $selectedCompanyId = session("selected_company_id");
                                if (
                                    $selectedCompanyId &&
                                    $selectedCompanyId !== "all"
                                ) {
                                    return $selectedCompanyId;
                                }
                                return null;
                            })
                            ->hidden(function () {
                                $selectedCompanyId = session("selected_company_id");
                                return $selectedCompanyId &&
                                    $selectedCompanyId !== "all";
                            })
                            ->required(function () {
                                $selectedCompanyId = session("selected_company_id");
                                return !(
                                    $selectedCompanyId &&
                                    $selectedCompanyId === "all"
                                );
                            })
                            ->searchable()
                            ->preload()
                            ->columnSpanFull(),
                        Select::make('recipient_id')
                            ->label(__('Recipient'))
                            ->relationship('recipient', 'name')
                            ->options(\App\Models\Contact::limit(10)->pluck('name', 'id'))
                            ->searchable()
                            ->preload()
                            ->required(),
                        DatePicker::make('date')
                            ->label(__('Advance Date'))
                            ->required()
                            ->default(now()),
                        TextInput::make('reference_no')
                            ->maxLength(255)
                            ->label(__('Reference Number'))
                            ->nullable()
                            ->default(null),
                        (new static)->getCodeField('advance_number', __('Advance Number')),
                        Select::make('from_account_id')
                            ->label(__('Cash/Bank Account'))
                            ->options(function () {
                                $selectedCompanyId = session('selected_company_id');
                                $query = \App\Models\Account::where('is_header', false)
                                    ->where('is_active', true)
                                    ->where('is_cash_bank', true);

                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where(function ($q) use ($selectedCompanyId) {
                                        $q->where('company_id', $selectedCompanyId)
                                            ->orWhereNull('company_id');
                                    });
                                }

                                return $query->orderBy('code')
                                    ->limit(100)
                                    ->get()
                                    ->mapWithKeys(fn ($account) => [
                                        $account->id => "{$account->code} - {$account->name}",
                                    ]);
                            })
                            ->getSearchResultsUsing(function (string $search) {
                                $selectedCompanyId = session('selected_company_id');
                                $query = \App\Models\Account::where('is_header', false)
                                    ->where('is_active', true)
                                    ->where('is_cash_bank', true)
                                    ->where(function ($query) use ($search) {
                                        $query->where('code', 'like', "%{$search}%")
                                            ->orWhere('name', 'like', "%{$search}%");
                                    });

                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where(function ($q) use ($selectedCompanyId) {
                                        $q->where('company_id', $selectedCompanyId)
                                            ->orWhereNull('company_id');
                                    });
                                }

                                return $query->orderBy('code')
                                    ->limit(50)
                                    ->get()
                                    ->mapWithKeys(fn ($account) => [
                                        $account->id => "{$account->code} - {$account->name}",
                                    ]);
                            })
                            ->getOptionLabelUsing(function ($value) {
                                $account = \App\Models\Account::find($value);
                                return $account ? "{$account->code} - {$account->name}" : $value;
                            })
                            ->searchable()
                            ->preload()
                            ->required()
                            ->helperText(__('Select a cash/bank account from the Chart of Accounts.')),
                        Textarea::make('description')
                            ->rows(1)
                            ->maxLength(65535)
                            ->label(__('Description')),
                    ])
                    ->columns(3)
                    ->columnSpanFull(),

                // Advance Disbursement Items
                Repeater::make('items')
                    ->relationship()
                    ->hiddenLabel()
                    ->addActionLabel(__('Add New Item'))
                    ->defaultItems(1)
                    ->live()
                    ->afterStateUpdated(function ($set, $get) {
                        $items = $get('items') ?? [];
                        $total = 0;
                        foreach ($items as $item) {
                            $amt = $item['amount'] ?? 0;
                            if (is_string($amt)) {
                                $amt = str_replace(['.', ','], ['', '.'], $amt);
                            }
                            $total += is_numeric($amt) ? (float) $amt : 0;
                        }
                        $set('total', $total);
                    })
                    ->table([
                        TableColumn::make('Transaction Classification')->width('25%')->alignment(Alignment::Start),
                        TableColumn::make('Amount')->width('20%')->alignment(Alignment::End),
                        TableColumn::make('Description')->width('35%')->alignment(Alignment::Start),
                        TableColumn::make('Total')->width('20%')->alignment(Alignment::End),
                    ])
                    ->schema([
                        Select::make('transaction_classification_id')
                            ->required()
                            ->searchable()
                            ->preload()
                            ->dehydrated(true)
                            ->label(__('Transaction Classification'))
                            ->options(function () {
                                $selectedCompanyId = session('selected_company_id');
                                $query = \App\Models\TransactionClassification::where('is_active', true);

                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where(function ($q) use ($selectedCompanyId) {
                                        $q->where('company_id', $selectedCompanyId)
                                            ->orWhereNull('company_id');
                                    });
                                }

                                return $query->orderBy('code')
                                    ->limit(100)
                                    ->get()
                                    ->mapWithKeys(fn ($classification) => [
                                        $classification->id => "{$classification->code} - {$classification->name}",
                                    ]);
                            })
                            ->getSearchResultsUsing(function (string $search) {
                                $selectedCompanyId = session('selected_company_id');
                                $query = \App\Models\TransactionClassification::where('is_active', true)
                                    ->where(function ($query) use ($search) {
                                        $query->where('code', 'like', "%{$search}%")
                                            ->orWhere('name', 'like', "%{$search}%");
                                    });

                                if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                    $query->where(function ($q) use ($selectedCompanyId) {
                                        $q->where('company_id', $selectedCompanyId)
                                            ->orWhereNull('company_id');
                                    });
                                }

                                return $query->orderBy('code')
                                    ->limit(50)
                                    ->get()
                                    ->mapWithKeys(fn ($classification) => [
                                        $classification->id => "{$classification->code} - {$classification->name}",
                                    ]);
                            })
                            ->getOptionLabelUsing(function ($value) {
                                $classification = \App\Models\TransactionClassification::find($value);
                                return $classification ? "{$classification->code} - {$classification->name}" : $value;
                            }),
                        NumberInput::make('amount')
                            ->required()
                            ->label(__('Amount'))
                            ->decimal(true)
                            ->live()
                            ->dehydrated(true)
                            ->extraInputAttributes(['style' => 'text-align:right']),
                        Textarea::make('description')
                            ->label(__('Description'))
                            ->rows(1)
                            ->maxLength(65535)
                            ->dehydrated(true),
                        Placeholder::make('total_display')
                            ->label(__('Total'))
                            ->content(function ($get) {
                                $amount = $get('amount') ?? 0;
                                if (is_string($amount)) {
                                    $amount = str_replace(['.', ','], ['', '.'], $amount);
                                }
                                $total = is_numeric($amount) ? (float) $amount : 0;
                                return number_format($total, 2, ',', '.');
                            })
                            ->extraAttributes([
                                'class' => 'font-semibold text-green-600 py-2 px-3 bg-gray-50 rounded-md border border-gray-200'
                            ]),
                    ])
                    ->reorderable()
                    ->cloneable()
                    ->collapsible()
                    ->compact()
                    ->columnSpan('full'),

                Section::make()
                    ->schema([
                        Placeholder::make('empty_col_1')
                            ->hiddenLabel()
                            ->columnSpan(1),
                        NumberInput::make('total')
                            ->label(__('Total Advance Disbursement'))
                            ->required()
                            ->decimal(true)
                            ->live()
                            ->dehydrated(true)
                            ->inlineLabel()
                            ->extraInputAttributes(['style' => 'text-align:right'])
                            ->disabled()
                            ->afterStateUpdated(function ($state, callable $set, callable $get) {
                                $items = $get('items') ?? [];
                                $calculatedTotal = 0;
                                foreach ($items as $item) {
                                    $amt = $item['amount'] ?? 0;
                                    if (is_string($amt)) {
                                        $amt = str_replace(['.', ','], ['', '.'], $amt);
                                    }
                                    $calculatedTotal += is_numeric($amt) ? (float) $amt : 0;
                                }
                                if ($calculatedTotal > 0) {
                                    $set('total', $calculatedTotal);
                                }
                            })
                            ->columnSpan(2),
                        Placeholder::make('empty_col_2')
                            ->hiddenLabel()
                            ->columnSpan(1),
                        TextInput::make('status')
                            ->label(__('Status'))
                            ->default('draft')
                            ->columnSpan(2),
                    ])
                    ->columns(2)
                    ->columnSpanFull(),

            ]);
    }
}
