<?php

namespace App\Filament\Resources\Banks\Schemas;

use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;

class BankForm
{
    use HasAutoGeneratedCode;

    protected function getDocumentType(): string
    {
        return 'bank';
    }

    protected function getCodeFieldName(): string
    {
        return 'code';
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema->components([
            Section::make(__('Bank Information'))
                ->schema([
                    (new static)->getCodeField('code', __('Bank Code'))
                        ->rule('required'),
                    TextInput::make('name')
                        ->label(__('Bank Name'))
                        ->required()
                        ->maxLength(200)
                        ->columnSpanFull(),
                    TextInput::make('country')
                        ->label(__('Country'))
                        ->default('Indonesia')
                        ->readonly()
                        ->required()
                        ->maxLength(100),
                    TextInput::make('clearing_code')
                        ->label(__('Clearing Code'))
                        ->maxLength(20),
                    TextInput::make('skn_code')
                        ->label(__('SKN Code'))
                        ->maxLength(20),
                    Toggle::make('is_active')
                        ->label(__('Active'))
                        ->default(true),
                ])
                ->columns(2),
        ]);
    }
}
