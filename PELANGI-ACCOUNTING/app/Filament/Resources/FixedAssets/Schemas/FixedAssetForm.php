<?php

namespace App\Filament\Resources\FixedAssets\Schemas;

use App\Models\FixedAsset;
use App\Traits\HasAutoGeneratedCode;
use Filament\Forms\Components\DatePicker;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Schema;
use Filament\Support\RawJs;

class FixedAssetForm
{
    use HasAutoGeneratedCode;

    /**
     * Get the document type for fixed assets
     */
    protected function getDocumentType(): string
    {
        return 'fixed_asset';
    }

    /**
     * Get the code field name for fixed assets
     */
    protected function getCodeFieldName(): string
    {
        return 'code';
    }
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                Section::make('Informasi Harta Tetap')
                    ->schema([
                        TextInput::make('name')
                            ->required()
                            ->maxLength(200)
                            ->columnSpanFull(),
                        (new static)->getCodeField('code', 'Kode Aset')
                            ->rule('required')
                            ->rule(function (?FixedAsset $record) {
                                return function (string $attribute, $value, \Closure $fail) use ($record) {
                                    $query = FixedAsset::where('code', $value);

                                    if ($record && $record->id) {
                                        // Editing: exclude current record
                                        $query->where('id', '!=', $record->id);
                                    }

                                    // Scope to the same company
                                    if ($record && $record->company_id) {
                                        $query->where('company_id', $record->company_id);
                                    } else {
                                        $companyId = session('selected_company_id') ?? auth()->user()->companies()->first()?->id;
                                        $query->where('company_id', $companyId);
                                    }

                                    if ($query->exists()) {
                                        $fail(__('The :attribute has already been taken.'));
                                    }
                                };
                            }),
                        Textarea::make('description')
                            ->columnSpanFull()
                            ->maxLength(65535),
                        Select::make('category_id')
                            ->relationship(
                                'category',
                                'name',
                                modifyQueryUsing: function ($query) {
                                    $selectedCompanyId = session('selected_company_id');
                                    if ($selectedCompanyId && $selectedCompanyId !== 'all') {
                                        $query->where('company_id', $selectedCompanyId);
                                    }
                                    return $query;
                                }
                            )
                            ->required()
                            ->searchable()
                            ->preload()
                            ->label('Kategori Aset'),
                        DatePicker::make('acquisition_date')
                            ->required()
                            ->label('Tanggal Perolehan'),
                        TextInput::make('acquisition_value')
                            ->numeric()
                            ->prefix('Rp')
                            ->required()
                            ->mask(RawJs::make('$money($input, \',\')'))
                            ->stripCharacters('.')
                            ->label('Nilai Perolehan'),
                        TextInput::make('book_value')
                            ->numeric()
                            ->prefix('Rp')
                            ->required()
                            ->mask(RawJs::make('$money($input, \',\', \'.\')'))
                            ->stripCharacters('.')
                            ->label('Nilai Buku'),
                        Select::make('company_id')
                            ->relationship(
                                name: 'company',
                                titleAttribute: 'name',
                                modifyQueryUsing: function ($query) {
                                    $user = auth()->user();
                                    if ($user) {
                                        $userCompanyIds = $user->companies()->pluck('companies.id');
                                        if ($userCompanyIds->isNotEmpty()) {
                                            $query->whereIn('companies.id', $userCompanyIds);
                                        } else {
                                            // If user has no assigned companies, return no results
                                            $query->whereRaw('1 = 0');
                                        }
                                    }
                                }
                            )
                            ->default(function () {
                                $selectedCompanyId = session('selected_company_id');
                                $user = auth()->user();
                                if ($selectedCompanyId) {
                                    // Verify user has access to this company
                                    if ($user && $user->companies()->where('companies.id', $selectedCompanyId)->exists()) {
                                        return $selectedCompanyId;
                                    }
                                }
                                return null;
                            })
                            ->hidden()
                            ->searchable()
                            ->preload()
                            ->required()
                            ->label('Perusahaan'),
                        Toggle::make('is_active')
                            ->required()
                            ->default(true)
                            ->label('Aktif'),
                        Toggle::make('create_acquisition_transaction')
                            ->label('Buat Transaksi Perolehan')
                            ->helperText('Buat transaksi perolehan otomatis dengan jurnal')
                            ->default(true)
                            ->visibleOn('create'),
                    ])
                    ->columns(2),
            ]);
    }
}
