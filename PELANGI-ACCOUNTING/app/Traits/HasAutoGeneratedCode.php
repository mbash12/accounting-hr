<?php

namespace App\Traits;

use App\Services\CodeGeneratorService;
use Filament\Actions\Action;
use Filament\Forms\Components\TextInput;
use Illuminate\Support\Facades\Auth;

trait HasAutoGeneratedCode
{
    /**
     * Get the document type for code generation
     * This should be implemented in the using class
     *
     * @return string
     */
    abstract protected function getDocumentType(): string;

    /**
     * Get code field name (defaults to 'code')
     *
     * @return string
     */
    protected function getCodeFieldName(): string
    {
        return 'code';
    }

    /**
     * Should auto-generate code on form load
     *
     * @return bool
     */
    protected function shouldAutoGenerateOnLoad(): bool
    {
        return true;
    }

    /**
     * Should disable the code field after generation
     *
     * @return bool
     */
    protected function shouldDisableCodeField(): bool
    {
        return true;
    }

    /**
     * Get company ID for multi-tenant setups
     *
     * @return int|null
     */
    protected function getCompanyId(): ?int
    {
        // First check if model has company_id attribute
        if (isset($this->attributes['company_id']) && $this->attributes['company_id']) {
            return (int) $this->attributes['company_id'];
        }
        
        $selectedCompanyId = session('selected_company_id');

        // Return null if 'all' is selected or no company is selected
        if (!$selectedCompanyId || $selectedCompanyId === 'all') {
            return null;
        }

        return (int) $selectedCompanyId;
    }

    /**
     * Check if auto-generation is enabled for this document type
     *
     * @return bool
     */
    protected function isAutoGenerateEnabled(): bool
    {
        $service = app(CodeGeneratorService::class);
        $status = $service->getDocumentStatus($this->getDocumentType(), $this->getCompanyId());

        return $status && ($status['is_active'] ?? false);
    }

    /**
     * Get code field with auto-generation functionality
     *
     * @param string|null $name
     * @param string|null $label
     * @return TextInput
     */
    public function getCodeField(?string $name = null, ?string $label = null): TextInput
    {
        $fieldName = $name ?? $this->getCodeFieldName();
        $fieldLabel = $label ?? __('Code');

        $isAutoGenerateEnabled = $this->isAutoGenerateEnabled();

        $field = TextInput::make($fieldName)
            ->label($fieldLabel)
            ->required()
            ->disabled(false)
            ->dehydrated();

        // Only add auto-generation functionality if enabled
        if ($isAutoGenerateEnabled) {
            $field->default(function () {
                if ($this->shouldAutoGenerateOnLoad()) {
                    return $this->generateNewCode();
                }
                return null;
            })
            ->suffixAction(
                Action::make('regenerate')
                    ->label(__('Generate'))
                    ->icon('heroicon-m-arrow-path')
                    ->action(function ($set) {
                        $set($this->getCodeFieldName(), $this->generateNewCode());
                    })
            );
        }

        return $field;
    }

    /**
     * Generate new code using the service
     *
     * @return string|null
     */
    protected function generateNewCode(): ?string
    {
        $service = app(CodeGeneratorService::class);

        // Generate code without updating counter for preview in form
        return $service->generateCodeManual(
            $this->getDocumentType(),
            $this->getCompanyId()
        );
    }

    /**
     * Generate and save code (updates counter)
     *
     * @return string|null
     */
    public function generateAndSaveCode(): ?string
    {
        $service = app(CodeGeneratorService::class);

        return $service->generateCode(
            $this->getDocumentType(),
            $this->getCompanyId()
        );
    }

  
    
    /**
     * Boot the trait and add automatic code generation if needed
     */
    public static function bootHasAutoGeneratedCode(): void
    {
        static::creating(function ($model) {
            if (method_exists($model, 'generateAndSaveCode') &&
                $model->getCodeFieldName() &&
                $model->isAutoGenerateEnabled()) {
                $field = $model->getCodeFieldName();

                $service = app(CodeGeneratorService::class);
                $preview = $service->previewNextCode($model->getDocumentType(), $model->getCompanyId());

                if (empty($model->{$field}) || ($preview && $model->{$field} === $preview)) {
                    $model->{$field} = $model->generateAndSaveCode();
                }
            }
        });
    }

    /**
     * Get all available document types for reference
     *
     * @return array
     */
    public function getAvailableDocumentTypes(): array
    {
        return [
            'advance_disbursement' => 'Advance Disbursement',
            'advance_receipt' => 'Advance Receipt',
            'cash_disbursement' => 'Cash Disbursement',
            'cash_receipt' => 'Cash Receipt',
            'cash_transfer' => 'Cash Transfer',
            'check_disbursement' => 'Check Disbursement',
            'delivery_document' => 'Delivery Document',
            'fixed_asset_transaction' => 'Fixed Asset Transaction',
            'goods_receipt' => 'Goods Receipt',
            'inventory_adjustment' => 'Inventory Adjustment',
            'journal_entry' => 'Journal Entry',
            'overpayment_receipt' => 'Overpayment Receipt',
            'overpayment_refund' => 'Overpayment Refund',
            'payable_payment' => 'Payable Payment',
            'purchase_invoice' => 'Purchase Invoice',
            'purchase_order' => 'Purchase Order',
            'purchase_return' => 'Purchase Return',
            'receivable_payment' => 'Receivable Payment',
            'sales_invoice' => 'Sales Invoice',
            'sales_order' => 'Sales Order',
            'sales_return' => 'Sales Return',
            'stock_opname' => 'Stock Opname',
            'warehouse_transfer' => 'Warehouse Transfer',
            'product' => 'Product',
            'fixed_asset' => 'Fixed Asset',
            'unit_measurement' => 'Unit of Measurement',
            'bank_account' => 'Bank Account',
            'warehouse' => 'Warehouse',
            'department' => 'Department',
            'tax' => 'Tax',
            'expedition' => 'Expedition',
            'contact' => 'Contact',
            'supplier' => 'Supplier',
            'customer' => 'Customer',
            'bank' => 'Bank',
            'business_type' => 'Business Type',
            'payment_term' => 'Payment Term',
        ];
    }
}
